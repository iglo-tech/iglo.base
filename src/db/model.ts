// Upstream: core/db_model.go
//
// BaseModel also declares what dbx learns from Go struct tags (see
// dbx/struct.ts): its "id" column. Models that embed it add their columns.

import type { Params, Row } from "@/db/dbx/query";
import type { PostScanner, StructModel, TableModel } from "@/db/dbx/struct";

// Model defines an interface with common methods that all db models should have.
//
// Note: for simplicity composite pk are not supported.
export interface Model extends TableModel {
  pk(): unknown;
  lastSavedPK(): unknown;
  isNew(): boolean;
  markAsNew(): void;
  markAsNotNew(): void;
}

// BaseModel defines a base class that is intended to be extended by other models.
export abstract class BaseModel implements Model, StructModel, PostScanner {
  private lastSavedPKValue = "";

  // Id is the primary key of the model.
  // It is usually autogenerated by the parent model implementation.
  id = "";

  abstract tableName(): string;

  // LastSavedPK returns the last saved primary key of the model.
  //
  // Its value is updated to the latest PK value after MarkAsNotNew() or PostScan() calls.
  lastSavedPK(): string {
    return this.lastSavedPKValue;
  }

  pk(): string {
    return this.id;
  }

  // IsNew indicates what type of db query (insert or update)
  // should be used with the model instance.
  isNew(): boolean {
    return this.lastSavedPKValue === "";
  }

  // MarkAsNew clears the pk field and marks the current model as "new"
  // (aka. forces m.IsNew() to be true).
  markAsNew(): void {
    this.lastSavedPKValue = "";
  }

  // MarkAsNew set the pk field to the Id value and marks the current model
  // as NOT "new" (aka. forces m.IsNew() to be false).
  markAsNotNew(): void {
    this.lastSavedPKValue = this.id;
  }

  // PostScan implements the [dbx.PostScanner] interface.
  //
  // It is usually executed right after the model is populated with the db row values.
  postScan(): void {
    this.markAsNotNew();
  }

  dbColumns(): Params {
    return { id: this.id };
  }

  dbScan(row: Row): void {
    if (Object.hasOwn(row, "id")) {
      this.id = row.id === null || row.id === undefined ? "" : String(row.id);
    }
  }
}
