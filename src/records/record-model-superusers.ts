// Upstream: core/record_model_superusers.go (CollectionNameSuperusers,
// DefaultInstallerEmail, IsSuperuser and the record checks of
// registerSuperuserHooks)
//
// IsSuperuser is a Record method in Go; the Record class
// (record-model.ts) exposes this function as isSuperuser().
//
// registerSuperuserHooks binds its record handlers to the _superusers
// collection; there is no hook system (D5), so they are the steps below,
// which src/records/record-save.ts calls at their place in the record
// chain. The superusers collection handler (OnCollectionCreateExecute /
// UpdateExecute) belongs to the collection save path. Not here: the
// installer's password reset mail check (OnMailerRecordPasswordResetSend,
// the mails task).
//
// The installer cleanup looks the installer up through upstream's root app
// (the app the hook was bound to), whose concurrent pool never sees an
// open transaction's writes: here app.databases.committedReads(). It
// deletes through the chain's app (upstream's e.App).

import { wrapError } from "@/collections/view";
import type { Record } from "@/records/record-model";
import { countRecords, findAuthRecordByEmail, type RecordsApp } from "@/records/record-query";
import { deleteStep, inTransaction, isNoRows, type Next, type Step } from "@/records/record-save";
import { newBadRequestError } from "@/server/error";

export const CollectionNameSuperusers = "_superusers";

// DefaultInstallerEmail is the default superuser email address
// for the initial autogenerated superuser account.
export const DefaultInstallerEmail = "__pbinstaller@example.com";

// IsSuperuser returns whether the current record is a superuser, aka.
// whether the record is from the _superusers collection.
export function recordIsSuperuser(m: Record): boolean {
  return m.collection().name === CollectionNameSuperusers;
}

// OnRecordDelete(_superusers) (-99): the last superuser cannot be deleted.
export function* superusersOnDelete(app: RecordsApp, record: Record, next: Next): Step {
  if (!recordIsSuperuser(record)) {
    yield* next(app);
    return;
  }

  yield* inTransaction(app, function* (txApp) {
    let total: number;
    try {
      total = countRecords(txApp, CollectionNameSuperusers);
    } catch (err) {
      throw wrapError("failed to fetch total superusers count", err);
    }

    if (total === 1) {
      throw newBadRequestError("You can't delete the only existing superuser", null);
    }

    yield* next(txApp);
  });
}

// OnRecordCreateExecute(_superusers) (-99): superusers are always
// verified, and creating another superuser deletes the installer one.
export function* superusersOnCreateExecute(app: RecordsApp, record: Record, next: Next): Step {
  yield* superusersSaveExecute(app, record, true, next);
}

// OnRecordUpdateExecute(_superusers) (-99): superusers are always verified.
export function* superusersOnUpdateExecute(app: RecordsApp, record: Record, next: Next): Step {
  yield* superusersSaveExecute(app, record, false, next);
}

function* superusersSaveExecute(
  app: RecordsApp,
  record: Record,
  isCreate: boolean,
  next: Next,
): Step {
  if (!recordIsSuperuser(record)) {
    yield* next(app);
    return;
  }

  record.setVerified(true); // always mark superusers as verified

  yield* next(app);

  // ensure that the installer superuser is deleted
  if (isCreate && record.email() !== DefaultInstallerEmail) {
    let installer: Record;
    try {
      installer = findAuthRecordByEmail(
        { ...app, databases: app.databases.committedReads() },
        CollectionNameSuperusers,
        DefaultInstallerEmail,
      );
    } catch (err) {
      if (!isNoRows(err)) {
        app.logger.error("Failed to fetch installer superuser", err);
      }
      // else already deleted
      return;
    }

    try {
      yield* deleteStep(app, installer);
    } catch (err) {
      app.logger.error("Failed to delete installer superuser", err);
    }
  }
}
