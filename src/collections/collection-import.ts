// Upstream: core/collection_import.go
//
// Errors are thrown (Go's returned error). The imported maps are values as
// Go's json.Unmarshal into map[string]any gives them (numbers, strings,
// booleans, null, arrays and objects); json.Marshal writes them with the
// go-json encoder before each is unmarshaled into its Collection.
//
// A validation failure is reported with the serialized validation errors
// in the message, indented as Go's jsontext.WithIndent("  ") writes them.

import { Collection } from "@/collections/collection-model";
import {
  type CollectionsApp,
  collectionQuery,
  findCollectionByNameOrId,
  runInAppTransaction,
} from "@/collections/collection-query";
import { deleteCollection, saveCollectionNoValidate } from "@/collections/collection-save";
import { newCollectionValidator } from "@/collections/collection-validate";
import { withDriverErrors } from "@/collections/driver-error";
import { wrapError } from "@/collections/view";
import { NoRowsError } from "@/db/dbx/rows";
import { goQuote } from "@/fields/field";
import { toString } from "@/tools/types/cast";
import {
  anyType,
  isJSONMarshaler,
  mapOf,
  marshal,
  sliceOf,
  unmarshal,
} from "@/tools/types/go-json";
import { Errors, NewError } from "@/validation/error";

// ImportCollectionsByMarshaledJSON is the same as [ImportCollections]
// but accept marshaled json array as import data (usually used for the autogenerated snapshots).
export function importCollectionsByMarshaledJSON(
  app: CollectionsApp,
  rawSliceOfMaps: string | Uint8Array,
  deleteMissing: boolean,
): void {
  const data =
    (unmarshal(rawSliceOfMaps, sliceOf(mapOf(anyType))) as
      | (Record<string, unknown> | null)[]
      | undefined) ?? [];

  importCollections(app, data, deleteMissing);
}

// ImportCollections imports the provided collections data in a single transaction.
//
// For existing matching collections, the imported data is unmarshaled on top of the existing model.
//
// NB! If deleteMissing is true, ALL NON-SYSTEM COLLECTIONS AND SCHEMA FIELDS,
// that are not present in the imported configuration, WILL BE DELETED
// (this includes their related records data).
export function importCollections(
  app: CollectionsApp,
  toImport: readonly (Record<string, unknown> | null)[],
  deleteMissing: boolean,
): void {
  if (toImport.length === 0) {
    // prevent accidentally deleting all collections
    throw new Error("no collections to import");
  }

  const importedCollections: Collection[] = [];
  const mappedImported = new Map<string, Collection>();

  // normalize imported collections data to ensure that all
  // collection fields are present and properly initialized
  for (const data of toImport) {
    let imported: Collection;

    let identifier = toString(data?.id);
    if (identifier === "") {
      identifier = toString(data?.name);
    }

    let existing: Collection | null = null;
    try {
      existing = withDriverErrors(() => findCollectionByNameOrId(app, identifier));
    } catch (err) {
      if (!(err instanceof NoRowsError)) {
        throw err;
      }
    }

    if (existing !== null) {
      // refetch for deep copy
      imported = withDriverErrors(() => findCollectionByNameOrId(app, existing.id));

      // ensure that the fields will be cleared
      if (data !== null && (data.fields === null || data.fields === undefined) && deleteMissing) {
        data.fields = [];
      }

      const rawData = marshal(data);

      // load the imported data
      imported.unmarshalJSON(rawData);

      // extend with the existing fields if necessary
      for (const f of existing.fields) {
        if (!f.getSystem() && deleteMissing) {
          continue;
        }
        if (imported.fields.getById(f.getId()) === null) {
          // replace with the existing id to prevent accidental column deletion
          // since otherwise the imported field will be treated as a new one
          const found = imported.fields.getByName(f.getName());
          if (found !== null && found.type() === f.type()) {
            found.setId(f.getId());
          }
          imported.fields.add(f);
        }
      }
    } else {
      imported = new Collection();

      const rawData = marshal(data);

      // load the imported data
      imported.unmarshalJSON(rawData);
    }

    imported.integrityChecks(false);

    importedCollections.push(imported);
    mappedImported.set(imported.id, imported);
  }

  // reorder views last since the view query could depend on some of the other collections
  importedCollections.sort((a, b) => {
    const cmpA = a.isView() ? 1 : -1;
    const cmpB = b.isView() ? 1 : -1;

    let res = cmpA < cmpB ? -1 : cmpA > cmpB ? 1 : 0;
    if (res === 0) {
      res = a.created.compare(b.created);
      if (res === 0) {
        res = a.updated.compare(b.updated);
      }
    }
    return res;
  });

  runInAppTransaction(app, (txApp) => {
    const existingCollections = withDriverErrors(() =>
      collectionQuery(txApp)
        .orderBy("updated ASC")
        .all<Collection>(() => new Collection()),
    );
    const mappedExisting = new Map<string, Collection>();
    for (const existing of existingCollections) {
      existing.integrityChecks(false);
      mappedExisting.set(existing.id, existing);
    }

    // delete old collections not available in the new configuration
    // (before saving the imports in case a deleted collection name is being reused)
    if (deleteMissing) {
      for (const existing of existingCollections) {
        if (mappedImported.has(existing.id) || existing.system) {
          continue; // exist or system
        }

        // delete collection
        deleteCollection(txApp, existing);
      }
    }

    // upsert imported collections
    for (const imported of importedCollections) {
      try {
        saveCollectionNoValidate(txApp, imported);
      } catch (err) {
        throw wrapError(`failed to save collection ${goQuote(imported.name)}`, err);
      }
    }

    // run validations
    for (const imported of importedCollections) {
      const original = mappedExisting.get(imported.id) ?? imported;

      const validator = newCollectionValidator(txApp, imported, original);
      const err = validator.run();
      if (err !== null) {
        // serialize the validation error(s)
        const serializedErr = indentJSON(isJSONMarshaler(err) ? marshal(err) : "{}", "  ");

        throw new Errors({
          collections: NewError(
            "validation_collections_import_failure",
            `Data validations failed for collection ${goQuote(imported.name)} (${imported.id}):\n${serializedErr}`,
          ),
        });
      }
    }
  });
}

// jsontext's multiline output with WithIndent(indent) and no prefix: each
// object member and array element on its own line, a space after each
// colon, empty objects and arrays kept as {} and [].
function indentJSON(compact: string, indent: string): string {
  let out = "";
  let depth = 0;
  let inString = false;
  for (let i = 0; i < compact.length; i++) {
    const c = compact[i] as string;
    if (inString) {
      out += c;
      if (c === "\\") {
        out += compact[++i] ?? "";
      } else if (c === '"') {
        inString = false;
      }
      continue;
    }
    switch (c) {
      case '"':
        inString = true;
        out += c;
        break;
      case "{":
      case "[": {
        const close = c === "{" ? "}" : "]";
        if (compact[i + 1] === close) {
          out += c + close;
          i++;
          break;
        }
        depth++;
        out += c + "\n" + indent.repeat(depth);
        break;
      }
      case "}":
      case "]":
        depth--;
        out += "\n" + indent.repeat(depth) + c;
        break;
      case ",":
        out += ",\n" + indent.repeat(depth);
        break;
      case ":":
        out += ": ";
        break;
      default:
        out += c;
    }
  }
  return out;
}
