// Upstream: core/collection_model.go (the model part)
//
// Go's Collection embeds baseCollection, collectionAuthOptions and
// collectionViewOptions, so their fields are promoted; here they are all
// properties of Collection. `new Collection()` is Go's zero value
// (core.Collection{}); the factories load the defaults.
//
// Not here: registerCollectionHooks (there is no hook system; the save,
// delete and validate steps are called directly by their tasks),
// onCollectionSave, onCollectionSaveExecute, onCollectionDeleteExecute and
// updateGeneratedIdIfExists (M1.7).
//
// dbExport returns the same values as upstream's DBExport (FieldsList,
// string[], DateTime, JSONRaw or the `{}` text); each has the db driver
// value upstream writes (FieldsList.value(), jsonArrayValue,
// DateTime.value(), JSONRaw.value()). DBExport's app argument is unused
// upstream and left out, as src/db's DBExporter has none.

