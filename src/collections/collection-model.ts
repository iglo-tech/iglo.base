// database/sql's conversion of a column value into a Go string
function scanString(v: unknown, column: string): string {
  if (v === null || v === undefined) {
    throw new Error(
      `sql: Scan error on column ${goQuote(column)}: converting NULL to string is unsupported`,
    );
  }
  if (typeof v === "string" || v instanceof Uint8Array) {
    return bytesToText(v);
  }
  return String(v);
}

// database/sql's conversion of a column value into a Go bool
// (driver.Bool: 1/0, booleans and strconv.ParseBool strings)
function scanBool(v: unknown, column: string): boolean {
  if (typeof v === "boolean") {
    return v;
  }
  if (typeof v === "number" || typeof v === "bigint") {
    if (v === 1 || v === 1n) {
      return true;
    }
    if (v === 0 || v === 0n) {
      return false;
    }
  }
  if (typeof v === "string" || v instanceof Uint8Array) {
    switch (bytesToText(v)) {
      case "1":
      case "t":
      case "T":
      case "true":
      case "TRUE":
      case "True":
        return true;
      case "0":
      case "f":
      case "F":
      case "false":
      case "FALSE":
      case "False":
        return false;
    }
  }
  throw new Error(
    `sql: Scan error on column ${goQuote(column)}: couldn't convert ${goQuote(String(v))} into type bool`,
  );
}

// strings.EqualFold: equal under Unicode simple case folding
function equalFold(s: string, t: string): boolean {
  const a = [...s];
  const b = [...t];
  if (a.length !== b.length) {
    return false;
  }
  for (let i = 0; i < a.length; i++) {
    const r = (a[i] as string).codePointAt(0) as number;
    const tr = (b[i] as string).codePointAt(0) as number;
    if (r === tr) {
      continue;
    }
    // follow r's fold orbit looking for tr
    let f = SimpleFold(r);
    while (f !== r && f !== tr) {
      f = SimpleFold(f);
    }
    if (f !== tr) {
      return false;
    }
  }
  return true;
}
