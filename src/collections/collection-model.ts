export const CollectionTypeBase = "base";
export const CollectionTypeAuth = "auth";
export const CollectionTypeView = "view";

// Collection defines the table, fields and various options related to a set of records.
export class Collection
  extends BaseModel
  implements FieldCollection, CollectionAuthOptions, CollectionViewOptions
{
  // ---------------------------------------------------------------
  // baseCollection

  // unexported in Go (read by the save and delete steps, M1.7)
  disableIntegrityChecks = false;
  autogeneratedId = "";

  listRule: string | null = null;
  viewRule: string | null = null;
  createRule: string | null = null;
  updateRule: string | null = null;
  deleteRule: string | null = null;

  // RawOptions represents the raw serialized collection option loaded from the DB.
  // NB! This field shouldn't be modified manually. It is automatically updated
  // with the collection type specific option before save.
  rawOptions = new JSONRaw();

  name = "";
  type = "";
  fields = new FieldsList();
  // types.JSONArray[string]; a nil slice is an empty array (both marshal
  // as [])
  indexes: string[] = [];
  created = new DateTime();
  updated = new DateTime();

  // System prevents the collection rename, deletion and rules change.
  // It is used primarily for internal purposes for collections like "_superusers", "_externalAuths", etc.
  system = false;

  // ---------------------------------------------------------------
  // collectionAuthOptions (see collection-model-auth-options.ts)

  authRule: string | null = null;
  manageRule: string | null = null;
  authAlert = new AuthAlertConfig();
  oauth2 = new OAuth2Config();
  passwordAuth = new PasswordAuthConfig();
  mfa = new MFAConfig();
  otp = new OTPConfig();
  authToken = new TokenConfig();
  passwordResetToken = new TokenConfig();
  emailChangeToken = new TokenConfig();
  verificationToken = new TokenConfig();
  fileToken = new TokenConfig();
  verificationTemplate = new EmailTemplate();
  resetPasswordTemplate = new EmailTemplate();
  confirmEmailChangeTemplate = new EmailTemplate();

  // ---------------------------------------------------------------
  // collectionViewOptions (see collection-model-view-options.ts)

  viewQuery = "";

  // TableName returns the Collection model SQL table name.
  tableName(): string {
    return "_collections";
  }

  // BaseFilesPath returns the storage dir path used by the collection.
  baseFilesPath(): string {
    return this.id;
  }

  // IsBase checks if the current collection has "base" type.
  isBase(): boolean {
    return this.type === CollectionTypeBase;
  }

  // IsAuth checks if the current collection has "auth" type.
  isAuth(): boolean {
    return this.type === CollectionTypeAuth;
  }

  // IsView checks if the current collection has "view" type.
  isView(): boolean {
    return this.type === CollectionTypeView;
  }

  // IntegrityChecks toggles the current collection integrity checks (ex. checking references on delete).
  integrityChecks(enable: boolean): void {
    this.disableIntegrityChecks = !enable;
  }

  // PostScan implements the dbx PostScanner interface to auto unmarshal
  // the raw serialized options into the concrete type specific fields.
  override postScan(): void {
    super.postScan();

    this.unmarshalRawOptions();
  }

  private unmarshalRawOptions(): void {
    const raw = this.rawOptions.marshalJSON();

    switch (this.type) {
      case CollectionTypeView:
        unmarshalViewOptions(this, raw);
        return;
      case CollectionTypeAuth:
        unmarshalAuthOptions(this, raw);
        return;
    }
  }

  // UnmarshalJSON implements the json.Unmarshaler interface.
  //
  // For new/"blank" Collection models it replaces the model with a factory
  // instance and then unmarshal the provided data one on top of it.
  unmarshalJSON(b: string | Uint8Array): void {
    // initialize the default fields
    // (e.g. in case the collection was NOT created using the designated factories)
    if (this.isNew() && this.type === "") {
      const minimal = { type: "", name: "", id: "" };
      unmarshalGoStruct(
        b,
        {
          type: (raw) => (minimal.type = decodeString(raw)),
          name: (raw) => (minimal.name = decodeString(raw)),
          id: (raw) => (minimal.id = decodeString(raw)),
        },
        () => {},
      );

      const blank = newCollection(minimal.type, minimal.name, minimal.id);
      Object.assign(this, blank);
    }

    // json.Unmarshal into the alias type (no UnmarshalJSON method):
    // the members of all embedded structs
    unmarshalGoStruct(
      b,
      {
        ...authOptionsDecoders(this),
        ...viewOptionsDecoders(this),
        ...this.baseDecoders(),
      },
      () => Object.assign(this, new Collection()),
    );
  }

  // the members of baseCollection (and BaseModel's id)
  private baseDecoders(): MemberDecoders {
    return {
      id: (raw) => (this.id = decodeString(raw)),
      listRule: (raw) => (this.listRule = decodeNullableString(raw)),
      viewRule: (raw) => (this.viewRule = decodeNullableString(raw)),
      createRule: (raw) => (this.createRule = decodeNullableString(raw)),
      updateRule: (raw) => (this.updateRule = decodeNullableString(raw)),
      deleteRule: (raw) => (this.deleteRule = decodeNullableString(raw)),
      name: (raw) => (this.name = decodeString(raw)),
      type: (raw) => (this.type = decodeString(raw)),
      fields: (raw) => this.fields.unmarshalJSON(raw),
      indexes: (raw) =>
        (this.indexes = (decodeAs(raw, sliceOf(stringType)) as string[] | undefined) ?? []),
      created: (raw) => {
        const d = new DateTime();
        d.unmarshalJSON(raw);
        this.created = d;
      },
      updated: (raw) => {
        const d = new DateTime();
        d.unmarshalJSON(raw);
        this.updated = d;
      },
      system: (raw) => (this.system = decodeBool(raw)),
    };
  }

  // the members of baseCollection in the Go struct order
  private baseMembers(): [string, unknown][] {
    return [
      ["id", this.id],
      ["listRule", this.listRule],
      ["viewRule", this.viewRule],
      ["createRule", this.createRule],
      ["updateRule", this.updateRule],
      ["deleteRule", this.deleteRule],
      ["name", this.name],
      ["type", this.type],
      ["fields", this.fields],
      ["indexes", this.indexes],
      ["created", this.created],
      ["updated", this.updated],
      ["system", this.system],
    ];
  }

  // MarshalJSON implements the json.Marshaler interface.
  //
  // Note that non-type related fields are ignored from the serialization
  // (ex. for "view" collections the "auth" fields are skipped).
  marshalJSON(): string {
    switch (this.type) {
      case CollectionTypeView:
        return marshalStruct([...this.baseMembers(), ...viewOptionsMembers(this)]);
      case CollectionTypeAuth:
        // hide secret keys from the serialization (and ensure that the
        // OAuth2 providers are always returned as array)
        return marshalStruct([...this.baseMembers(), ...authOptionsMembers(this, true)]);
      default:
        return marshalStruct(this.baseMembers());
    }
  }

  // String returns a string representation of the current collection
  // ("" when it cannot be marshaled).
  string(): string {
    try {
      return this.marshalJSON();
    } catch {
      return "";
    }
  }

  override toString(): string {
    return this.string();
  }

  // DBExport prepares and exports the current collection data for db persistence.
  dbExport(): Params {
    const result: Params = {
      id: this.id,
      type: this.type,
      listRule: this.listRule,
      viewRule: this.viewRule,
      createRule: this.createRule,
      updateRule: this.updateRule,
      deleteRule: this.deleteRule,
      name: this.name,
      fields: this.fields,
      indexes: this.indexes,
      system: this.system,
      created: this.created,
      updated: this.updated,
      options: `{}`,
    };

    switch (this.type) {
      case CollectionTypeView:
        result.options = parseJSONRaw({ marshalJSON: () => marshalViewOptions(this) });
        break;
      case CollectionTypeAuth:
        result.options = parseJSONRaw({ marshalJSON: () => marshalAuthOptions(this) });
        break;
    }

    return result;
  }

  // the dbx struct columns (Go's `db` tags)
  override dbColumns(): Params {
    return {
      ...super.dbColumns(),
      listRule: this.listRule,
      viewRule: this.viewRule,
      createRule: this.createRule,
      updateRule: this.updateRule,
      deleteRule: this.deleteRule,
      options: this.rawOptions,
      name: this.name,
      type: this.type,
      fields: this.fields,
      indexes: this.indexes,
      created: this.created,
      updated: this.updated,
      system: this.system,
    };
  }

  // populates the collection from a `_collections` row as Go's
  // database/sql scan does (the Scanner types scan themselves; a NULL
  // into a string or bool is an error)
  override dbScan(row: Row): void {
    const has = (column: string): boolean => Object.hasOwn(row, column);

    if (has("id")) {
      this.id = scanString(row.id, "id");
    }
    for (const column of ["listRule", "viewRule", "createRule", "updateRule", "deleteRule"]) {
      if (has(column)) {
        const v = row[column];
        const rule = v === null || v === undefined ? null : scanString(v, column);
        switch (column) {
          case "listRule":
            this.listRule = rule;
            break;
          case "viewRule":
            this.viewRule = rule;
            break;
          case "createRule":
            this.createRule = rule;
            break;
          case "updateRule":
            this.updateRule = rule;
            break;
          case "deleteRule":
            this.deleteRule = rule;
            break;
        }
      }
    }
    if (has("options")) {
      const raw = new JSONRaw();
      raw.scan(row.options);
      this.rawOptions = raw;
    }
    if (has("name")) {
      this.name = scanString(row.name, "name");
    }
    if (has("type")) {
      this.type = scanString(row.type, "type");
    }
    if (has("fields")) {
      this.fields.scan(row.fields);
    }
    if (has("indexes")) {
      try {
        this.indexes = scanJSONArray<string>(row.indexes, stringType);
      } catch (err) {
        this.indexes = [];
        throw err;
      }
    }
    if (has("created")) {
      const d = new DateTime();
      d.scan(row.created);
      this.created = d;
    }
    if (has("updated")) {
      const d = new DateTime();
      d.scan(row.updated);
      this.updated = d;
    }
    if (has("system")) {
      this.system = scanBool(row.system, "system");
    }
  }

  // GetIndex returns s single Collection index expression by its name.
  getIndex(name: string): string {
    for (const idx of this.indexes) {
      if (equalFold(parseIndex(idx).indexName, name)) {
        return idx;
      }
    }

    return "";
  }

  // AddIndex adds a new index into the current collection.
  //
  // If the collection has an existing index matching the new name it will be replaced with the new one.
  addIndex(name: string, unique: boolean, columnsExpr: string, optWhereExpr: string): void {
    this.removeIndex(name);

    let idx = "CREATE ";
    if (unique) {
      idx += "UNIQUE ";
    }
    idx += "INDEX `" + name + "` ";
    idx += "ON `" + this.name + "` (";
    idx += columnsExpr;
    idx += ")";
    if (optWhereExpr !== "") {
      idx += " WHERE " + optWhereExpr;
    }

    this.indexes.push(idx);
  }

  // RemoveIndex removes a single index with the specified name from the current collection.
  removeIndex(name: string): void {
    for (const [i, idx] of this.indexes.entries()) {
      if (equalFold(parseIndex(idx).indexName, name)) {
        this.indexes.splice(i, 1);
        return;
      }
    }
  }

  // setDefaultAuthOptions (core/collection_model_auth_options.go)
  setDefaultAuthOptions(): void {
    setDefaultAuthOptions(this);
  }

  idChecksum(): string {
    return "pbc_" + crc32Checksum(this.type + this.name);
  }

  initDefaultId(): void {
    if (this.id === "") {
      this.id = this.idChecksum();
      this.autogeneratedId = this.id;
    }
  }

  initDefaultFields(): void {
    switch (this.type) {
      case CollectionTypeBase:
        this.initIdField();
        break;
      case CollectionTypeAuth:
        this.initIdField();
        this.initPasswordField();
        this.initTokenKeyField();
        this.initEmailField();
        this.initEmailVisibilityField();
        this.initVerifiedField();
        break;
      case CollectionTypeView:
        // view fields are autogenerated
        break;
    }
  }

  private initIdField(): void {
    const existing = this.fields.getByName(FieldNameId);
    const field = existing instanceof TextField ? existing : null;
    if (field === null) {
      // create default field
      const created = new TextField({
        name: FieldNameId,
        system: true,
        primaryKey: true,
        required: true,
        min: 15,
        max: 15,
        pattern: defaultLowercaseRecordIdPattern,
        autogeneratePattern: `[a-z0-9]{15}`,
      });

      // prepend it
      this.fields = newFieldsList(created, ...this.fields);
    } else {
      // enforce system defaults
      field.system = true;
      field.required = true;
      field.primaryKey = true;
      field.hidden = false;
      if (field.pattern === "") {
        field.pattern = defaultLowercaseRecordIdPattern;
      }
    }
  }

  private initPasswordField(): void {
    const existing = this.fields.getByName(FieldNamePassword);
    const field = existing instanceof PasswordField ? existing : null;
    if (field === null) {
      // load default field
      this.fields.add(
        new PasswordField({
          name: FieldNamePassword,
          system: true,
          hidden: true,
          required: true,
          min: 8,
        }),
      );
    } else {
      // enforce system defaults
      field.system = true;
      field.hidden = true;
      field.required = true;
    }
  }

  private initTokenKeyField(): void {
    const existing = this.fields.getByName(FieldNameTokenKey);
    const field = existing instanceof TextField ? existing : null;
    if (field === null) {
      // load default field
      this.fields.add(
        new TextField({
          name: FieldNameTokenKey,
          system: true,
          hidden: true,
          min: 30,
          max: 60,
          required: true,
          autogeneratePattern: `[a-zA-Z0-9]{50}`,
        }),
      );
    } else {
      // enforce system defaults
      field.system = true;
      field.hidden = true;
      field.required = true;
    }

    // ensure that there is a unique index for the field
    const [, ok] = findSingleColumnUniqueIndex(this.indexes, FieldNameTokenKey);
    if (!ok) {
      this.indexes.push(
        "CREATE UNIQUE INDEX `" +
          this.fieldIndexName(FieldNameTokenKey) +
          "` ON `" +
          this.name +
          "` (`" +
          FieldNameTokenKey +
          "`)",
      );
    }
  }

  private initEmailField(): void {
    const existing = this.fields.getByName(FieldNameEmail);
    const field = existing instanceof EmailField ? existing : null;
    if (field === null) {
      // load default field
      this.fields.add(
        new EmailField({
          name: FieldNameEmail,
          system: true,
          required: true,
        }),
      );
    } else {
      // enforce system defaults
      field.system = true;
      field.hidden = false; // managed by the emailVisibility flag
    }

    // ensure that there is a unique index for the email field
    const [, ok] = findSingleColumnUniqueIndex(this.indexes, FieldNameEmail);
    if (!ok) {
      this.indexes.push(
        "CREATE UNIQUE INDEX `" +
          this.fieldIndexName(FieldNameEmail) +
          "` ON `" +
          this.name +
          "` (`" +
          FieldNameEmail +
          "`) WHERE `" +
          FieldNameEmail +
          "` != ''",
      );
    }
  }

  private initEmailVisibilityField(): void {
    const existing = this.fields.getByName(FieldNameEmailVisibility);
    const field = existing instanceof BoolField ? existing : null;
    if (field === null) {
      // load default field
      this.fields.add(
        new BoolField({
          name: FieldNameEmailVisibility,
          system: true,
        }),
      );
    } else {
      // enforce system defaults
      field.system = true;
    }
  }

  private initVerifiedField(): void {
    const existing = this.fields.getByName(FieldNameVerified);
    const field = existing instanceof BoolField ? existing : null;
    if (field === null) {
      // load default field
      this.fields.add(
        new BoolField({
          name: FieldNameVerified,
          system: true,
        }),
      );
    } else {
      // enforce system defaults
      field.system = true;
    }
  }

  // the index name for a field: at most 64 bytes, as Go slices the
  // string's bytes (a cut inside a multi-byte character leaves invalid
  // UTF-8 bytes, kept as lone surrogates)
  fieldIndexName(field: string): string {
    let name = "idx_" + field + "_";

    if (this.id !== "") {
      name += this.id;
    } else if (this.name !== "") {
      name += this.name;
    } else {
      name += pseudorandomStringWithAlphabet(10, defaultIdAlphabet);
    }

    const bytes = textToBytes(name);
    if (bytes.length > 64) {
      return bytesToText(bytes.subarray(0, 64));
    }

    return name;
  }
}

// NewCollection initializes and returns a new Collection model with the specified type and name.
//
// It also loads the minimal default configuration for the collection
// (eg. system fields, indexes, type specific options, etc.).
export function newCollection(typ: string, name: string, optId = ""): Collection {
  switch (typ) {
    case CollectionTypeAuth:
      return newAuthCollection(name, optId);
    case CollectionTypeView:
      return newViewCollection(name, optId);
    default:
      return newBaseCollection(name, optId);
  }
}

// NewBaseCollection initializes and returns a new "base" Collection model.
//
// It also loads the minimal default configuration for the collection
// (eg. system fields, indexes, type specific options, etc.).
export function newBaseCollection(name: string, optId = ""): Collection {
  const m = new Collection();
  m.name = name;
  m.type = CollectionTypeBase;
  m.id = optId;

  m.initDefaultId();
  m.initDefaultFields();

  return m;
}

