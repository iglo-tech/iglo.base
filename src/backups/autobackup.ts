// Upstream: core/backup.go (registerAutobackupHooks)
//
// loadAutobackupJob runs at the end of bootstrap and on each settings reload
// (the OnBootstrap and OnSettingsReload hooks, D5): each run removes and adds
// the job, so its position in GET /api/crons is upstream's.

import type { App } from "@/app/app";
import { createBackup, generateBackupName } from "@/backups/create";
import { sendSystemAlertToAllSuperusers } from "@/backups/system-alert";
import type { System } from "@/tools/filesystem/filesystem";

const jobId = "__pbAutoBackup__";

const autoPrefix = "@auto_pb_backup_";

function errorText(err: unknown): string {
  return err instanceof Error ? err.message : String(err);
}

export function loadAutobackupJob(app: App): void {
  const rawSchedule = app.settings.Backups.Cron;
  if (rawSchedule === "") {
    app.cron.remove(jobId);
    return;
  }

  try {
    app.cron.add(jobId, rawSchedule, () => runAutobackup(app));
  } catch {
    // as upstream: an invalid expression (settings validate it) keeps the old job
  }
}

async function runAutobackup(app: App): Promise<void> {
  const name = generateBackupName(app, autoPrefix);

  try {
    await createBackup(app, name);
  } catch (err) {
    app.logger.error(`[Backup cron] Failed to create backup: ${name}`, err);

    try {
      await sendSystemAlertToAllSuperusers(
        app,
        "Autobackup failure",
        "Failed to create/upload automated backup. Raw error:\n" + errorText(err),
      );
    } catch (alertError) {
      app.logger.warn(`[Backup cron] Failed to send backup error alerts: ${name}`, alertError);
    }
  }

  const maxKeep = Number(app.settings.Backups.CronMaxKeep);

  if (maxKeep === 0) {
    return; // no explicit limit
  }

  let fsys: System;
  try {
    fsys = app.filesystem.newBackupsFilesystem();
  } catch (err) {
    app.logger.error("[Backup cron] Failed to initialize the backup filesystem", err);
    return;
  }

  try {
    let files;
    try {
      files = fsys.list(autoPrefix);
    } catch (err) {
      app.logger.error("[Backup cron] Failed to list autogenerated backups", err);
      return;
    }

    if (maxKeep >= files.length) {
      return; // nothing to remove
    }

    // sort desc
    files.sort((a, b) => (a.modTime > b.modTime ? -1 : a.modTime < b.modTime ? 1 : 0));

    // keep only the most recent n auto backup files
    for (const f of files.slice(maxKeep)) {
      try {
        fsys.delete(f.key);
      } catch (err) {
        app.logger.error(`[Backup cron] Failed to remove old autogenerated backup: ${f.key}`, err);
      }
    }
  } finally {
    fsys.close();
  }
}
