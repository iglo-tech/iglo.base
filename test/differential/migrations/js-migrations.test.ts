// JavaScript migrations against the reference PocketBase v0.41.0 binary.
// Not part of `bun test`: run `bun run test:reference`.
//
//   - the JS patterns of upstream's docs (patterns.ts) run on both servers
//     with the same output and the same pb_data, up and down;
//   - the ways a migration file can fail give the same exit code and text;
//   - `migrate` gives the same output, exit code and prompts, with and
//     without a terminal's answers;
//   - the same collection API calls write the same files and `_migrations`
//     rows, and a collection import writes none;
//   - files generated by either server, applied on a fresh pb_data by the
//     other, give the same schema, `_collections` and `_migrations`.

import { Database } from "bun:sqlite";
import { afterAll, describe, expect, test } from "bun:test";
import { chmodSync, existsSync, mkdirSync, mkdtempSync, readdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import {
  api,
  kinds,
  type Kind,
  newSite,
  normalizeOutput,
  readMigrations,
  runIn,
  serveSite,
  type Site,
  writeMigrations,
} from "@test/differential/migrations/support";
import { patternFiles } from "@test/differential/migrations/patterns";
import { diffSnapshots, takeSnapshot } from "@test/differential/roundtrip/snapshot";

const timeout = 120_000;

const root = mkdtempSync(join(tmpdir(), "iglo-base-js-migrations-"));

afterAll(() => {
  rmSync(root, { recursive: true, force: true });
});

function site(kind: Kind): Site {
  return newSite(kind, root);
}

function query<T>(s: Site, sql: string): T[] {
  const db = new Database(join(s.dataDir, "data.db"), { readonly: true });
  try {
    return db.query(sql).all() as T[];
  } finally {
    db.close();
  }
}

function userMigrations(s: Site): string[] {
  return query<{ file: string }>(
    s,
    "SELECT file FROM _migrations WHERE file NOT LIKE '%.go' ORDER BY file",
  ).map((r) => r.file);
}

function normalizedRun(
  s: Site,
  result: { exitCode: number; stdout: string; stderr: string },
): unknown {
  return {
    exitCode: result.exitCode,
    stdout: normalizeOutput(result.stdout, s),
    stderr: normalizeOutput(result.stderr, s),
  };
}

function tables(s: Site): unknown[] {
  return query(
    s,
    "SELECT type, name, sql FROM sqlite_schema WHERE name NOT LIKE 'sqlite_%' ORDER BY name",
  );
}

function collections(s: Site): unknown[] {
  return query(
    s,
    "SELECT id, name, type, system, listRule, viewRule, createRule, updateRule, deleteRule, indexes FROM _collections ORDER BY name",
  );
}

// Nothing carries over from a start: every generated value is normalized.
// pb_data's top level differs by design: upstream also writes types.d.ts
// and .notify, which hold no data. The `applied` times differ by nature;
// userMigrations compares the files.
function snapshotDiff(control: Site, subject: Site): string[] {
  const options = { start: { contains: () => false }, startedAt: "2000-01-01 00:00:00.000Z" };
  return diffSnapshots(
    takeSnapshot(control.dataDir, options),
    takeSnapshot(subject.dataDir, options),
  ).filter(
    (line) =>
      !/^pb_data: \w+ only: (types\.d\.ts|\.notify)$/.test(line) &&
      !line.startsWith("table _migrations: "),
  );
}

describe("patterns", () => {
  test(
    "up and down give the same output and pb_data",
    async () => {
      const [upstream, iglo] = await Promise.all(kinds.map((kind) => Promise.resolve(site(kind))));
      const sites = [upstream as Site, iglo as Site];

      const ups = [];
      for (const s of sites) {
        writeMigrations(s, patternFiles);
        ups.push(normalizedRun(s, await runIn(s, ["migrate", "up"])));
      }
      expect(ups[1]).toEqual(ups[0]);
      expect((ups[0] as { exitCode: number }).exitCode).toBe(0);
      expect(userMigrations(sites[1] as Site)).toEqual(userMigrations(sites[0] as Site));

      const compareTables = (): void => {
        expect(tables(sites[1] as Site)).toEqual(tables(sites[0] as Site));
        expect(collections(sites[1] as Site)).toEqual(collections(sites[0] as Site));
      };
      compareTables();

      const params = (s: Site): unknown =>
        JSON.parse(
          new TextDecoder().decode(
            query<{ value: Uint8Array }>(s, "SELECT value FROM _params WHERE id = 'settings'")[0]
              ?.value,
          ),
        );
      expect(params(sites[1] as Site)).toEqual(params(sites[0] as Site));

      const downs = [];
      for (const s of sites) {
        downs.push(normalizedRun(s, await runIn(s, ["migrate", "down", "10"], "y\n")));
      }
      expect(downs[1]).toEqual(downs[0]);
      expect((downs[0] as { exitCode: number }).exitCode).toBe(0);
      compareTables();
      expect(userMigrations(sites[1] as Site)).toEqual(userMigrations(sites[0] as Site));

      // the null up recorded nothing to undo, and its down ran
      expect(
        query(sites[1] as Site, "SELECT name FROM sqlite_schema WHERE name = 'down_ran'"),
      ).toHaveLength(1);
    },
    timeout,
  );

  test(
    "serve applies them and the next start finds nothing pending",
    async () => {
      for (const kind of kinds) {
        const s = site(kind);
        writeMigrations(s, patternFiles);
        const first = await serveSite(s);
        const res = await fetch(`${first.url}/api/collections/posts/records`);
        expect(res.status).toBe(403); // listRule null
        await first.stop();
        const applied = query(s, "SELECT file, applied FROM _migrations ORDER BY file");
        const second = await serveSite(s);
        await second.stop();
        expect(query(s, "SELECT file, applied FROM _migrations ORDER BY file")).toEqual(applied);
      }
    },
    timeout,
  );
});

const failures: [string, string][] = [
  ["a thrown error", `migrate((app) => { throw new Error("boom") })`],
  ["a thrown string", `migrate((app) => { throw "str" })`],
  ["a thrown object", `migrate((app) => { throw {a:1} })`],
  ["a binding error", `migrate((app) => { app.findCollectionByNameOrId("nope") })`],
  ["a validation error", `migrate((app) => { app.save(new Collection({name:""})) })`],
  ["an undefined global", `migrate((app) => { nope() })`],
  ["a returned error", `migrate((app) => { return new Error("ret") })`],
  ["a returned value", `migrate((app) => { return 5 })`],
  ["a top-level throw", `throw new Error("top")`],
  ["a wrong migrate argument", `migrate("a")`],
  [
    "a failing nested transaction",
    `migrate((app) => { app.runInTransaction((tx) => { tx.db().newQuery("create table zz (a int)").execute(); throw new Error("in") }) })`,
  ],
  ["no migrate call", `var x = 1;`],
  ["no arguments", `migrate()`],
  ["two migrate calls", `migrate((app) => {}); migrate((app) => { throw new Error("second") })`],
  ["$os.exit", `migrate((app) => { $os.exit(3) })`],
];

describe("failures", () => {
  for (const [name, text] of failures) {
    test(
      name,
      async () => {
        const results = [];
        for (const kind of kinds) {
          const s = site(kind);
          writeMigrations(s, { "2_x.js": text });
          const result = await runIn(s, ["migrate", "up"]);
          // goja's stack trace of a panic
          const stderr = result.stderr
            .replace(/\n\ngoroutine [^]*$/, "\n")
            .replace(/ at [^ ]*\.func1 \(native\)/, "");
          results.push({
            run: normalizedRun(s, { ...result, stderr }),
            applied: existsSync(join(s.dataDir, "data.db")) ? userMigrations(s) : [],
          });
        }
        expect(results[1]).toEqual(results[0]);
      },
      timeout,
    );
  }

  test(
    "a syntax error panics on both",
    async () => {
      for (const kind of kinds) {
        const s = site(kind);
        writeMigrations(s, { "2_x.js": `migrate((app) => {` });
        const result = await runIn(s, ["migrate", "up"]);
        expect(result.exitCode).toBe(2);
        expect(result.stderr).toStartWith(
          "panic: registerMigrations: failed to run migration 2_x.js: SyntaxError: SyntaxError: ",
        );
      }
    },
    timeout,
  );
});

describe("the migrate command", () => {
  // each step runs on both servers, in order, on one site each
  const steps: { args: string[]; stdin?: string; files?: Record<string, string> }[] = [
    { args: ["migrate"] },
    { args: ["migrate", "up"] },
    { args: ["migrate", "--help"] },
    { args: ["migrate", "bogus"] },
    { args: ["migrate", "create"] },
    { args: ["migrate", "create", "NoTerminal"] },
    { args: ["migrate", "create", "NewFile Name"], stdin: "n\n" },
    { args: ["migrate", "create", "maybe"], stdin: "what\n\n" },
    { args: ["migrate", "create", "NewFile Name"], stdin: "y\n" },
    { args: ["migrate", "collections"], stdin: "yes\n" },
    { args: ["migrate", "collections", "ignored"] },
    { args: ["migrate", "up"] },
    { args: ["migrate", "down"] },
    { args: ["migrate", "down"], stdin: "n\n" },
    { args: ["migrate", "down", "1"], stdin: "y\n" },
    { args: ["migrate", "down", "0"], stdin: "y\n" },
    { args: ["migrate", "down", "abc"], stdin: "y\n" },
    { args: ["migrate", "history-sync"] },
    {
      args: ["migrate", "up"],
      files: {
        "3000000001_one.js": `migrate((app) => { app.db().newQuery("CREATE TABLE one (a INT)").execute() }, (app) => { app.db().newQuery("DROP TABLE one").execute() })`,
        "3000000002_two.js": `migrate((app) => { app.db().newQuery("CREATE TABLE two (a INT)").execute() }, null)`,
      },
    },
    { args: ["migrate", "up"] },
    { args: ["migrate", "down", "2"], stdin: "y\n" },
    { args: ["migrate", "up"] },
    { args: ["migrate", "--migrationsDir", "ROOT/none", "history-sync"] },
  ];

  test(
    "same output, exit codes and prompts",
    async () => {
      const sites = kinds.map((kind) => site(kind));
      for (const step of steps) {
        const results = [];
        for (const s of sites) {
          if (step.files !== undefined) {
            writeMigrations(s, step.files);
          }
          const args = step.args.map((arg) => arg.replace("ROOT", s.root));
          results.push(normalizedRun(s, await runIn(s, args, step.stdin)));
        }
        expect(cleanHelp(results[1])).toEqual(cleanHelp(results[0]));
      }
      expect(userMigrations(sites[1] as Site)).toEqual([]);
    },
    timeout,
  );
});

// the help's other flags, and the files made in the same second, whose
// order depends on the clock
function cleanHelp(result: unknown): unknown {
  const r = JSON.parse(
    JSON.stringify(result).replace(/(pocketbase|iglo-base) migrate/g, "BIN migrate"),
  ) as { stdout: string; stderr: string };
  const created = /TIME_(new_file_name|collections_snapshot)/g;
  return {
    ...r,
    stderr: r.stderr.replace(created, "CREATED").split("\n").toSorted().join("\n"),
    stdout: r.stdout
      .replace(created, "CREATED")
      .replace(/^ {6}--hooks\w+ .*\n/gm, "")
      .replace(/(--(dir|publicDir) string +.*\(default )".*"\)/g, '$1"DEFAULT")')
      .replace(/ +--/g, " --")
      .replace(/ {2,}/g, " ")
      .split("\n")
      .toSorted()
      .join("\n"),
  };
}

const generatedId = /"(id|collectionId)": "(pbc_[0-9]+|_clone_\w+)"/g;

async function expectStatus(res: Promise<Response>, status: number): Promise<void> {
  const done = await res;
  expect(`${done.status} ${done.status === status ? "" : await done.text()}`).toBe(`${status} `);
}

// the same collection API calls on a server
async function collectionCalls(s: Site): Promise<void> {
  const server = await serveSite(s);
  try {
    await expectStatus(
      api(server, "POST", "/api/collections", {
        id: "pbc_articles00001",
        type: "base",
        name: "articles",
        listRule: "",
        fields: [
          { id: "text00000000title", name: "title", type: "text", required: true },
          { id: "numb00000000count", name: "count", type: "number" },
        ],
        indexes: ["CREATE INDEX idx_title ON articles (title)"],
      }),
      200,
    );
    await expectStatus(
      api(server, "POST", "/api/collections", {
        id: "pbc_people0000001",
        type: "auth",
        name: "people",
        passwordAuth: { identityFields: ["email"] },
        ...tokens,
      }),
      200,
    );
    await expectStatus(
      api(server, "POST", "/api/collections", {
        id: "pbc_listing000001",
        type: "view",
        name: "listing",
        viewQuery: "SELECT id, email FROM users",
      }),
      200,
    );
    await expectStatus(
      api(server, "PATCH", "/api/collections/articles", {
        name: "posts",
        viewRule: "id != ''",
        fields: [
          { id: "text00000000title", name: "headline", type: "text", required: true },
          { id: "bool000000000flag", name: "flag", type: "bool" },
        ],
        indexes: [],
      }),
      200,
    );
    await expectStatus(
      api(server, "PATCH", "/api/collections/people", {
        otp: { enabled: true },
        authAlert: { enabled: false },
      }),
      200,
    );
    await expectStatus(api(server, "PATCH", "/api/collections/people", {}), 200);
    await expectStatus(api(server, "DELETE", "/api/collections/listing"), 204);
    // a failed change writes nothing
    await expectStatus(api(server, "POST", "/api/collections", { name: "" }), 400);
    await expectStatus(api(server, "DELETE", "/api/collections/missing"), 404);
    // a collection import writes nothing
    await expectStatus(
      api(server, "PUT", "/api/collections/import", {
        collections: [{ id: "pbc_imported00001", type: "base", name: "imported" }],
      }),
      204,
    );
    await expectStatus(api(server, "DELETE", "/api/collections/imported/truncate"), 204);
  } finally {
    await server.stop();
  }
}

const tokens = {
  authToken: { secret: "a".repeat(50) },
  fileToken: { secret: "a".repeat(50) },
  emailChangeToken: { secret: "a".repeat(50) },
  passwordResetToken: { secret: "a".repeat(50) },
  verificationToken: { secret: "a".repeat(50) },
};

function normalizeFile(text: string): string {
  return text.replace(generatedId, '"$1": "GENERATED"');
}

function normalizedFiles(s: Site): [string, string][] {
  return Object.entries(readMigrations(s)).map(([name, text]) => [
    name.replace(/^\d+/, "TIME"),
    normalizeFile(text),
  ]);
}

function normalizedRows(s: Site): string[] {
  return userMigrations(s).map((file) => file.replace(/^\d+/, "TIME"));
}

describe("automigrate", () => {
  test(
    "the same calls write the same files and rows, and cross-apply both ways",
    async () => {
      const upstream = site("upstream");
      const iglo = site("iglo.base");
      for (const s of [upstream, iglo]) {
        await collectionCalls(s);
      }

      const uploaded = normalizedFiles(upstream);
      expect(uploaded).toHaveLength(6);
      expect(normalizedFiles(iglo).toSorted()).toEqual(uploaded.toSorted());
      expect(normalizedRows(iglo).toSorted()).toEqual(normalizedRows(upstream).toSorted());

      // files generated by each server, applied by the other and by itself
      for (const [from, kind] of [
        [upstream, "iglo.base"],
        [iglo, "upstream"],
      ] as const) {
        const control = site(from.kind);
        const subject = site(kind);
        for (const s of [control, subject]) {
          writeMigrations(s, readMigrations(from));
          const result = await runIn(s, ["migrate", "up"]);
          expect(result.stderr).toBe("");
          expect(result.exitCode).toBe(0);
        }
        expect(userMigrations(subject)).toEqual(userMigrations(control));
        expect(snapshotDiff(control, subject)).toEqual([]);
      }

      // nothing is pending on the next run of the writer itself
      for (const s of [upstream, iglo]) {
        const result = await runIn(s, ["migrate", "up"]);
        expect(result.stdout).toBe("No new migrations to apply.\n");
      }
      expect(readdirSync(iglo.migrationsDir)).toHaveLength(6);
    },
    timeout * 2,
  );

  test(
    "a migration file that cannot be written does not change the response",
    async () => {
      const results = [];
      for (const kind of kinds) {
        const s = site(kind);
        mkdirSync(s.migrationsDir);
        chmodSync(s.migrationsDir, 0o555);
        const server = await serveSite(s);
        try {
          const res = await api(server, "POST", "/api/collections", { type: "base", name: "one" });
          const body = (await res.json()) as { name?: string };
          results.push({ status: res.status, name: body.name });
        } finally {
          await server.stop();
          chmodSync(s.migrationsDir, 0o755);
        }
        results.push(query(s, "SELECT count(*) AS n FROM _migrations WHERE file LIKE '%.js'"));
      }
      expect(results[2]).toEqual(results[0]);
      expect(results[3]).toEqual(results[1]);
    },
    timeout,
  );

  test(
    "a body that changes the id of an updated collection",
    async () => {
      const results = [];
      for (const kind of kinds) {
        const s = site(kind);
        const server = await serveSite(s);
        try {
          await api(server, "POST", "/api/collections", { type: "base", name: "one" });
          const res = await api(server, "PATCH", "/api/collections/one", { id: "other_id_value" });
          results.push({ status: res.status, body: await res.json() });
        } finally {
          await server.stop();
        }
      }
      expect(results[1]).toEqual(results[0]);
    },
    timeout,
  );
});
