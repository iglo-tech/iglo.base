// Reads a stopped server's pb_data into a Snapshot that two runs can compare
// (docs/design/03-data-compatibility.md, Verification). Everything is read
// from a copy, so a read can never change the data under test.
//
// A snapshot holds exact text: `quote()` of every cell (with its storage
// class and exact digits; a TEXT value `quote()` cannot show, because it has a
// NUL or invalid UTF-8, also carries its bytes), `sqlite_schema` without
// `rootpage`, the `storage/` tree with a checksum of every file and the text
// of every `.attrs`. Only the rules below replace a value, each because a
// server generates that value at random or from the clock, so two runs of the
// same scenario cannot agree on it. A rule replaces a value only if it has the
// value's exact format and, where a value can be carried over, is not in the
// starting data (or, for a timestamp, is not older than the run): a stored
// value that a server changes by mistake still differs.
//
//   timestamps     autodate fields, `_collections`/`_params` created and
//                  updated: the clock
//   record ids     `_authOrigins.id` and the ids the scenario left to the
//                  server (`generatedIds`): core.GenerateDefaultRandomId
//   tokenKey       the field's autogenerate pattern, per auth record
//   password       bcrypt's salt, and the hash that depends on it. The prefix
//                  stays: `$2a$` and the cost are the format
//   token secrets  `options.*Token.secret` of a new auth collection
//   file names     the random suffix of a stored name
//                  (`<base>_<10 chars>.<ext>`, tools/filesystem). A batch item
//                  uploads a file again under its normalized name, so that
//                  name has two (apis/batch.go), and the first shows in
//                  `.attrs` as the original name
//   view field ids `_clone_` + 4 random characters (core/view.go), unless in
//                  the starting data
//   ciphertext     `_params.settings` under --encryptionEnv: a random nonce.
//                  The value is decrypted with the run's key and the plain
//                  text compared, so the two storage forms stay apart
//
// A generated id or file name is replaced by a numbered placeholder in the
// order of first appearance, everywhere it occurs (relations, paths), so equal
// values must stay equal and different ones different.
//
// Two more values are compared by what they must keep, not by bytes:
//
//   sqlite_stat4   the one known schema difference (Bun's SQLite is built
//                  without STAT4, see Data compatibility): its schema row and
//                  rows are left out on both sides
//   new thumbs     a thumbnail iglo.base generated may differ in encoded bytes,
//                  never in format or size (Data compatibility, Thumbnails).
//                  Run.igloThumbs names them. Their `.attrs` are exact but for
//                  `md5`, which must be the checksum of their own bytes; every
//                  other thumbnail and `.attrs` is exact
//
// `_logs` is not compared (M5.5): auxiliary.db must only open, pass its
// integrity check and keep its schema; run.ts checks that the rows upstream
// wrote survive.

import { Database } from "bun:sqlite";
import { createDecipheriv, createHash } from "node:crypto";
import {
  cpSync,
  existsSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import type { StartingData } from "@test/differential/harness/compare";

export interface SnapshotOptions {
  // where the run started from
  start: StartingData;
  // the run's first moment, as a stored timestamp: an older value was not
  // generated by the run
  startedAt: string;
  // record ids the scenario left to the server
  generatedIds?: Iterable<string>;
  // the --encryptionEnv key of the run's last leg
  encryptionKey?: string;
  // storage paths (relative, as stored) of thumbnails iglo.base generated
  igloThumbs?: Set<string>;
}

interface ThumbEntry {
  format: string;
  // of the file
  sha256: string;
  attrs: string;
  // `.attrs` without its md5, which follows the encoded bytes
  attrsWithoutMd5: string;
  // whether `.attrs` holds the file's checksum
  md5Matches: boolean;
  fromIglo: boolean;
}

export interface Snapshot {
  // section name -> lines, in the order they compare
  sections: Map<string, string[]>;
  // normalized thumbnail path -> what is compared
  thumbs: Map<string, ThumbEntry>;
}

const timestamp = /^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}\.\d{3}Z$/;
const tokenKey = /^[A-Za-z0-9_]{50}$/;
const bcrypt = /^(\$2a\$\d\d\$)[./A-Za-z0-9]{53}$/;
const generatedId = /^[a-z0-9]{15}$/;
const fileName = /^(.*)_[a-z0-9]{10}((?:\.[^/]*)?)$/;
const batchFileName = /^(.*_[a-z0-9]{10})_[a-z0-9]{10}((?:\.[^/]*)?)$/;
// a word that can be a generated id or file name
const word = /[A-Za-z0-9_.-]+/g;
const secret = /("secret":")([A-Za-z0-9]{50})(")/g;
const cloneId = /"id":"(_clone_[A-Za-z0-9]{4})"/g;
const md5Member = /,?"md5":"[^"]*"/;

// the value of a `quote()` text literal, or undefined for any other cell
function unquote(cell: string): string | undefined {
  return cell.startsWith("'") && cell.endsWith("'")
    ? cell.slice(1, -1).replaceAll("''", "'")
    : undefined;
}

function quoted(text: string): string {
  return `'${text.replaceAll("'", "''")}'`;
}

function quoteIdent(name: string): string {
  return `"${name.replaceAll('"', '""')}"`;
}

function decryptSettings(cell: string, key: string): string {
  const data = Buffer.from(unquote(cell) ?? "", "base64");
  const decipher = createDecipheriv("aes-256-gcm", Buffer.from(key), data.subarray(0, 12));
  decipher.setAuthTag(data.subarray(data.length - 16));
  return Buffer.concat([decipher.update(data.subarray(12, -16)), decipher.final()]).toString();
}

interface FieldInfo {
  name: string;
  type: string;
}

// what each column of a table holds that a rule cares about
type ColumnRule = "timestamp" | "tokenKey" | "password" | "file" | "id";

function columnRules(db: Database): Map<string, Map<string, ColumnRule>> {
  const out = new Map<string, Map<string, ColumnRule>>();
  const rows = db.query("SELECT name, type, fields FROM _collections").all() as {
    name: string;
    type: string;
    fields: string;
  }[];
  for (const row of rows) {
    const columns = new Map<string, ColumnRule>();
    for (const field of JSON.parse(row.fields) as FieldInfo[]) {
      if (field.type === "autodate") {
        columns.set(field.name, "timestamp");
      } else if (field.type === "password") {
        columns.set(field.name, "password");
      } else if (field.type === "file") {
        columns.set(field.name, "file");
      } else if (field.name === "tokenKey" && row.type === "auth") {
        columns.set(field.name, "tokenKey");
      }
    }
    out.set(row.name, columns);
  }
  out.get("_authOrigins")?.set("id", "id");
  out.set(
    "_collections",
    new Map<string, ColumnRule>([
      ["created", "timestamp"],
      ["updated", "timestamp"],
    ]),
  );
  out.set(
    "_params",
    new Map<string, ColumnRule>([
      ["created", "timestamp"],
      ["updated", "timestamp"],
    ]),
  );
  return out;
}

class Normalizer {
  // a generated id or file name -> its placeholder
  readonly names = new Map<string, string>();
  private readonly seenStart = new Map<string, boolean>();

  constructor(private readonly options: SnapshotOptions) {
    for (const id of options.generatedIds ?? []) {
      this.names.set(id, `<id ${this.names.size}>`);
    }
  }

  private inStart(value: string): boolean {
    let known = this.seenStart.get(value);
    if (known === undefined) {
      known = this.options.start.contains(value);
      this.seenStart.set(value, known);
    }
    return known;
  }

  // first pass: replaces the column's generated value and learns the names
  cell(rule: ColumnRule | undefined, cell: string): string {
    const text = unquote(cell);
    if (rule === undefined || text === undefined) {
      return cell;
    }
    switch (rule) {
      case "timestamp":
        return timestamp.test(text) && text >= this.options.startedAt ? "<timestamp>" : cell;
      case "tokenKey":
        return tokenKey.test(text) && !this.inStart(text) ? "<tokenKey>" : cell;
      case "password": {
        const m = bcrypt.exec(text);
        return m !== null && !this.inStart(text) ? `${m[1] as string}<bcrypt>` : cell;
      }
      case "id":
        if (generatedId.test(text) && !this.inStart(text) && !this.names.has(text)) {
          this.names.set(text, `<id ${this.names.size}>`);
        }
        return cell;
      case "file":
        for (const name of text.startsWith("[") ? (JSON.parse(text) as string[]) : [text]) {
          const m = fileName.exec(name);
          if (m === null || this.names.has(name) || this.inStart(name)) {
            continue;
          }
          const batch = batchFileName.exec(name);
          if (batch === null) {
            this.names.set(name, `${m[1] as string}_<file ${this.names.size}>${m[2] as string}`);
          } else {
            const first = `${batch[1] as string}${batch[2] as string}`;
            const base = (batch[1] as string).slice(0, -11);
            const n = this.names.size;
            this.names.set(name, `${base}_<file ${n}>_<file ${n}>${batch[2] as string}`);
            this.names.set(first, `${base}_<file ${n}>${batch[2] as string}`);
          }
        }
        return cell;
    }
  }

  // second pass: every occurrence of a learned name
  replaceNames(text: string): string {
    return text.replace(word, (w) => this.names.get(w) ?? w);
  }

  storagePath(path: string): string {
    return path
      .split("/")
      .map((segment) => {
        const attrs = segment.endsWith(".attrs") ? ".attrs" : "";
        const base = attrs === "" ? segment : segment.slice(0, -attrs.length);
        const m = /^(thumbs_|\d+x\d+[tbf]?_)(.*)$/.exec(base);
        if (m !== null && this.names.has(m[2] as string)) {
          return (m[1] as string) + (this.names.get(m[2] as string) as string) + attrs;
        }
        return (this.names.get(base) ?? base) + attrs;
      })
      .join("/");
  }
}

// format and size from the header of the formats thumbnails are made from
function imageFormat(bytes: Uint8Array): string {
  const buf = Buffer.from(bytes);
  if (buf.subarray(1, 4).toString("latin1") === "PNG") {
    return `png ${buf.readUInt32BE(16)}x${buf.readUInt32BE(20)}`;
  }
  if (buf.subarray(0, 3).toString("latin1") === "GIF") {
    return `gif ${buf.readUInt16LE(6)}x${buf.readUInt16LE(8)}`;
  }
  if (buf[0] === 0xff && buf[1] === 0xd8) {
    let at = 2;
    while (at + 9 < buf.length) {
      const marker = buf[at + 1] as number;
      if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
        return `jpeg ${buf.readUInt16BE(at + 7)}x${buf.readUInt16BE(at + 5)}`;
      }
      at += 2 + buf.readUInt16BE(at + 2);
    }
  }
  return `other ${createHash("sha256").update(buf).digest("hex")}`;
}

// relative paths under dir, sorted; a directory ends with "/"
function walk(dir: string): string[] {
  const out: string[] = [];
  if (!existsSync(dir)) {
    return out;
  }
  for (const name of readdirSync(dir, { recursive: true, encoding: "utf8" })) {
    out.push(statSync(join(dir, name)).isDirectory() ? `${name}/` : name);
  }
  return out.toSorted();
}

// <collection>/<record>/thumbs_<file>/<size>_<file>; an original's own name can
// start with thumbs_ too
export function isThumb(path: string): boolean {
  const segments = path.split("/");
  return segments.length === 4 && (segments[2] as string).startsWith("thumbs_");
}

// raw paths of the thumbnails in a pb_data directory no server uses
export function thumbPaths(dataDir: string): Set<string> {
  return new Set(walk(join(dataDir, "storage")).filter((p) => isThumb(p) && !p.endsWith("/")));
}

function schemaLines(db: Database): string[] {
  const rows = db
    .query("SELECT type, name, tbl_name, sql FROM sqlite_schema ORDER BY rowid")
    .all() as { type: string; name: string; tbl_name: string; sql: string | null }[];
  return rows
    .filter((r) => r.name !== "sqlite_stat4")
    .map((r) => `${r.type} ${r.name} ${r.tbl_name} ${r.sql}`);
}

// a cell's `quote()` literal, with the bytes of a TEXT value it does not show
function exactCell(cell: string, hex: string | null): string {
  if (hex === null) {
    return cell;
  }
  const shown = Buffer.from(unquote(cell) ?? "").toString("hex");
  return shown.toUpperCase() === hex ? cell : `${cell} bytes ${hex}`;
}

// the rows of a table, each cell as exactCell gives it
function tableRows(db: Database, table: string): { columns: string[]; rows: string[][] } {
  const columns = (
    db.query(`SELECT name FROM pragma_table_info(${quoted(table)})`).all() as { name: string }[]
  ).map((c) => c.name);
  const select = ["quote(rowid)"];
  for (const column of columns.map(quoteIdent)) {
    select.push(
      `quote(${column})`,
      `CASE typeof(${column}) WHEN 'text' THEN hex(CAST(${column} AS BLOB)) END`,
    );
  }
  const rows = db
    .query(`SELECT ${select.join(", ")} FROM ${quoteIdent(table)} ORDER BY rowid`)
    .values() as (string | null)[][];
  return {
    columns,
    rows: rows.map((row) => [
      row[0] as string,
      ...columns.map((_, i) =>
        exactCell(row[2 * i + 1] as string, row[2 * i + 2] as string | null),
      ),
    ]),
  };
}

function readDataDb(path: string, normalizer: Normalizer, options: SnapshotOptions) {
  const sections = new Map<string, string[]>();
  const db = new Database(path);
  try {
    sections.set(
      "PRAGMA integrity_check",
      (db.query("PRAGMA integrity_check").values() as string[][]).map((r) => r[0] as string),
    );
    sections.set("sqlite_schema", schemaLines(db));

    const rules = columnRules(db);
    const tables = (
      db.query("SELECT name FROM sqlite_schema WHERE type = 'table' ORDER BY name").all() as {
        name: string;
      }[]
    )
      .map((t) => t.name)
      .filter((name) => name !== "sqlite_stat4");
    const dumps = new Map<string, string[][]>();
    for (const table of tables) {
      const { columns, rows } = tableRows(db, table);
      const tableRules = rules.get(table);
      dumps.set(
        table,
        rows.map((row) =>
          row.map((cell, i) => {
            const column = i === 0 ? "rowid" : (columns[i - 1] as string);
            let out = normalizer.cell(tableRules?.get(column), cell);
            if (
              table === "_params" &&
              column === "value" &&
              row[columnIndex(columns, "id")] === quoted("settings")
            ) {
              out = settingsCell(out, options.encryptionKey);
            }
            if (table === "_collections") {
              out = out.replace(secret, (m, open: string, value: string, close: string) =>
                options.start.contains(value) ? m : `${open}<secret>${close}`,
              );
              out = out.replace(cloneId, (m, id: string) =>
                options.start.contains(id) ? m : `"id":"_clone_<random>"`,
              );
            }
            return `${column}=${out}`;
          }),
        ),
      );
    }
    for (const [table, rows] of dumps) {
      sections.set(
        `table ${table}`,
        rows.map((row) => normalizer.replaceNames(row.join("\t"))),
      );
    }
  } finally {
    db.close();
  }
  return sections;
}

// the column's position in a `tableRows` row
function columnIndex(columns: string[], name: string): number {
  return columns.indexOf(name) + 1;
}

// plain settings are a BLOB; an encrypted value is base64 TEXT
function settingsCell(cell: string, key: string | undefined): string {
  if (key !== undefined && cell.startsWith("'")) {
    return `encrypted ${decryptSettings(cell, key)}`;
  }
  return cell.startsWith("X'") ? `plain ${Buffer.from(cell.slice(2, -1), "hex").toString()}` : cell;
}

function readAuxiliaryDb(path: string): string[] {
  const db = new Database(path);
  try {
    const check = db.query("PRAGMA integrity_check").values() as string[][];
    return [...check.map((r) => r[0] as string), ...schemaLines(db)];
  } finally {
    db.close();
  }
}

function readStorage(dataDir: string, normalizer: Normalizer, options: SnapshotOptions) {
  const dir = join(dataDir, "storage");
  const lines: string[] = [];
  const thumbs = new Map<string, ThumbEntry>();
  for (const path of walk(dir)) {
    const normalized = normalizer.storagePath(path);
    if (path.endsWith("/")) {
      lines.push(normalized);
      continue;
    }
    if (isThumb(path) && !path.endsWith(".attrs")) {
      const bytes = readFileSync(join(dir, path));
      const attrsPath = join(dir, `${path}.attrs`);
      const rawAttrs = existsSync(attrsPath) ? readFileSync(attrsPath, "utf8") : "";
      const attrs = normalizer.replaceNames(rawAttrs);
      const md5 = createHash("md5").update(bytes).digest("base64");
      thumbs.set(normalized, {
        format: imageFormat(bytes),
        sha256: createHash("sha256").update(bytes).digest("hex"),
        attrs,
        attrsWithoutMd5: attrs.replace(md5Member, ""),
        md5Matches: rawAttrs.includes(`"md5":"${md5}"`),
        fromIglo: options.igloThumbs?.has(path) ?? false,
      });
      continue;
    }
    if (path.endsWith(".attrs")) {
      if (isThumb(path) && existsSync(join(dir, path.slice(0, -".attrs".length)))) {
        continue; // with its thumbnail
      }
      lines.push(`${normalized} ${normalizer.replaceNames(readFileSync(join(dir, path), "utf8"))}`);
      continue;
    }
    const bytes = readFileSync(join(dir, path));
    lines.push(`${normalized} ${bytes.length} ${createHash("sha256").update(bytes).digest("hex")}`);
  }
  return { lines, thumbs };
}

// top-level names; the -wal and -shm files come and go with a connection
function topLevel(dataDir: string): string[] {
  return readdirSync(dataDir)
    .filter((name) => !name.endsWith("-wal") && !name.endsWith("-shm"))
    .toSorted();
}

export function takeSnapshot(dataDir: string, options: SnapshotOptions): Snapshot {
  const root = mkdtempSync(join(tmpdir(), "iglo-base-snapshot-"));
  try {
    const copy = join(root, "pb_data");
    cpSync(dataDir, copy, { recursive: true });
    const normalizer = new Normalizer(options);
    const sections = readDataDb(join(copy, "data.db"), normalizer, options);
    sections.set("auxiliary.db", readAuxiliaryDb(join(copy, "auxiliary.db")));
    sections.set("pb_data", topLevel(copy));
    const { lines, thumbs } = readStorage(copy, normalizer, options);
    sections.set("storage", lines);
    return { sections, thumbs };
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

const shownPerSection = 8;

function clip(line: string): string {
  return line.length > 600 ? `${line.slice(0, 600)}...` : line;
}

// Every difference between a control and a subject snapshot, grouped by
// section; empty when they agree.
export function diffSnapshots(control: Snapshot, subject: Snapshot): string[] {
  const out: string[] = [];
  const names = new Set([...control.sections.keys(), ...subject.sections.keys()]);
  for (const name of names) {
    const a = control.sections.get(name);
    const b = subject.sections.get(name);
    if (a === undefined || b === undefined) {
      out.push(`${name}: only in the ${a === undefined ? "subject" : "control"}`);
      continue;
    }
    const inA = new Set(a);
    const inB = new Set(b);
    const missing = a.filter((line) => !inB.has(line));
    const extra = b.filter((line) => !inA.has(line));
    for (const line of missing.slice(0, shownPerSection)) {
      out.push(`${name}: control only: ${clip(line)}`);
    }
    for (const line of extra.slice(0, shownPerSection)) {
      out.push(`${name}: subject only: ${clip(line)}`);
    }
    if (missing.length === 0 && extra.length === 0 && a.join("\n") !== b.join("\n")) {
      out.push(`${name}: same lines in a different order`);
    }
  }
  const paths = new Set([...control.thumbs.keys(), ...subject.thumbs.keys()]);
  for (const path of paths) {
    const a = control.thumbs.get(path);
    const b = subject.thumbs.get(path);
    if (a === undefined || b === undefined) {
      out.push(`thumbs: ${path}: only in the ${a === undefined ? "subject" : "control"}`);
      continue;
    }
    if (a.format !== b.format) {
      out.push(`thumbs: ${path}: format ${a.format} != ${b.format}`);
    }
    if (b.fromIglo) {
      if (a.attrsWithoutMd5 !== b.attrsWithoutMd5) {
        out.push(`thumbs: ${path}: .attrs ${a.attrsWithoutMd5} != ${b.attrsWithoutMd5}`);
      }
      if (!b.md5Matches) {
        out.push(`thumbs: ${path}: .attrs md5 is not the file's: ${b.attrs}`);
      }
      continue;
    }
    if (a.attrs !== b.attrs) {
      out.push(`thumbs: ${path}: .attrs ${a.attrs} != ${b.attrs}`);
    }
    if (a.sha256 !== b.sha256) {
      out.push(`thumbs: ${path}: bytes differ, and upstream wrote both`);
    }
  }
  return out;
}
