const timeout = 120_000;

type Kind = "upstream" | "igloBase";
const kinds: Kind[] = ["upstream", "igloBase"];

interface Server {
  url: string;
  stop(): Promise<unknown>;
}

interface Reply {
  status: number;
  json: { [key: string]: unknown };
}

const roots: string[] = [];

afterAll(() => {
  for (const root of roots) {
    rmSync(root, { recursive: true, force: true });
  }
});

function fixtureCopy(): string {
  const root = mkdtempSync(join(tmpdir(), "iglo-base-oauth2-flows-"));
  roots.push(root);
  const dataDir = join(root, "pb_data");
  copyDataDir(fixtureDir, dataDir);
  return dataDir;
}

const start = (kind: Kind, dataDir: string): Promise<Server> =>
  kind === "upstream" ? startUpstream({ dataDir }) : startServer([], dataDir);

async function api(
  server: Server,
  method: string,
  path: string,
  body?: unknown,
  headers: Record<string, string> = {},
): Promise<Reply> {
  const res = await fetch(server.url + path, {
    method,
    headers: { "Content-Type": "application/json", ...headers },
    ...(body === undefined ? {} : { body: JSON.stringify(body) }),
  });
  const text = await res.text();
  return { status: res.status, json: text === "" ? {} : (JSON.parse(text) as Reply["json"]) };
}

function signIn(
  server: Server,
  extra: { [key: string]: unknown } = {},
  headers: Record<string, string> = {},
  query = "",
): Promise<Reply> {
  return api(
    server,
    "POST",
    `/api/collections/users/auth-with-oauth2${query}`,
    { provider: "oidc", code: "123", redirectURL: "https://example.com", ...extra },
    headers,
  );
}

// the transcript as comparable text: tokens, record ids, timestamps and
// autogenerated usernames replaced, object members sorted
function scrub(transcript: unknown): string {
  const sorted = (value: unknown): unknown => {
    if (Array.isArray(value)) {
      return value.map(sorted);
    }
    if (value !== null && typeof value === "object") {
      return Object.fromEntries(
        Object.entries(value)
          .toSorted(([a], [b]) => (a < b ? -1 : 1))
          .map(([k, v]) => [k, sorted(v)]),
      );
    }
    return value;
  };
  return JSON.stringify(sorted(transcript), null, 2)
    .replace(/\beyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+/g, "<token>")
    .replace(/\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}\.\d{3}Z/g, "<date>")
    .replace(/"(id|recordRef|mfaId)": "[a-z0-9]{15}"/g, '"$1": "<id>"')
    .replace(/users[0-9]{5}/g, "<username>")
    .replace(/\b[A-Za-z0-9]{40}\b/g, "<client>");
}

// runs a flow on each server, on its own prepared fixture copy, one after
// the other, as the mock and the SMTP sink are shared; returns both transcripts
async function onBoth(
  flow: (server: Server, dataDir: string, kind: Kind) => Promise<unknown>,
  prepare: (ctx: { dataDir: string }) => void,
): Promise<void> {
  const transcripts: string[] = [];
  for (const kind of kinds) {
    const dataDir = fixtureCopy();
    prepare({ dataDir });
    const server = await start(kind, dataDir);
    try {
      transcripts.push(scrub(await flow(server, dataDir, kind)));
    } finally {
      await server.stop();
    }
  }
  expect(transcripts[1]).toBe(transcripts[0] as string);
}

// a client subscribed to @oauth2
async function oauth2Client(ctx: ScenarioContext): Promise<RealtimeStream> {
  const stream = await ctx.open();
  const res = await ctx.subscribe(stream.clientId, ["@oauth2"]);
  expect(res.status).toBe(204);
  return stream;
}

function externalAuthRows(dataDir: string): { [key: string]: unknown }[] {
  return queryRows(
    dataDir,
    "SELECT * FROM _externalAuths WHERE provider = 'oidc' ORDER BY providerId",
  ) as { [key: string]: unknown }[];
}

describe("the popup flow", () => {
  test(
    "the code goes from the redirect to the subscriber to the sign-in",
    async () => {
      let provider: MockProvider;
      await onBoth(
        async (server) => {
          const ctx = new ScenarioContext(server.url);
          try {
            const stream = await oauth2Client(ctx);
            const methods = await api(server, "GET", "/api/collections/users/auth-methods");
            const redirect = await request(
              server.url,
              `/api/oauth2-redirect?state=${stream.clientId}&code=from_provider`,
            );
            await stream.waitFor((e) => e.some((m) => m.event === "@oauth2"));
            const message = stream.events.find((m) => m.event === "@oauth2");
            const { code } = JSON.parse(message?.data ?? "{}") as { code: string };
            const auth = await signIn(server, { code });
            return {
              providers: (
                methods.json["oauth2"] as { providers: { name: string }[] }
              ).providers.map((p) => p.name),
              redirect: [redirect.status, redirect.headers.get("location")],
              message,
              auth,
              tokenRequest: provider.requests.findLast((r) => r.path === "/token")?.body,
            };
          } finally {
            ctx.close();
          }
        },
        useProvider({ user: { sub: "popup" } }, undefined, "users", (p) => {
          provider = p;
        }),
      );
    },
    timeout,
  );

  test(
    "(POST) a stored name doesn't reach another provider than Apple",
    async () => {
      await onBoth(
        async (server) => {
          const ctx = new ScenarioContext(server.url);
          try {
            const stream = await oauth2Client(ctx);
            const form = new URLSearchParams({
              state: stream.clientId,
              code: "test_code",
              user: `{"name":{"firstName":"test","lastName":"store_name"}}`,
            });
            const redirect = await request(server.url, "/api/oauth2-redirect", {
              method: "POST",
              headers: { "Content-Type": "application/x-www-form-urlencoded" },
              body: form.toString(),
            });
            const auth = await signIn(server, { code: "test_code" });
            expect(JSON.stringify(auth.json)).not.toContain("store_name");
            return { redirect: redirect.status, auth };
          } finally {
            ctx.close();
          }
        },
        useProvider({ user: { sub: "named" } }),
      );
    },
    timeout,
  );
});

describe("_externalAuths across the servers", () => {
  for (const [writer, reader] of [
    ["igloBase", "upstream"],
    ["upstream", "igloBase"],
  ] as [Kind, Kind][]) {
    test(
      `rows written by ${writer} are used and deleted by ${reader}`,
      async () => {
        const dataDir = fixtureCopy();
        useProvider({ user: { sub: "cross", ...verifiedEmail("cross@example.com") } })({ dataDir });

        // the writer signs a new user up and links it
        const first = await start(writer, dataDir);
        let created: Reply;
        try {
          created = await signIn(first);
        } finally {
          await first.stop();
        }
        expect(created.status).toBe(200);
        expect(created.json["meta"]).toMatchObject({ isNew: true });
        const recordId = (created.json["record"] as { id: string }).id;
        const token = created.json["token"] as string;

        const [row] = externalAuthRows(dataDir);
        expect(row).toMatchObject({
          collectionRef: "_pb_users_auth_",
          recordRef: recordId,
          provider: "oidc",
          providerId: "cross",
        });
        expect(row?.["id"]).toMatch(/^[a-z0-9]{15}$/);
        expect(row?.["created"]).toMatch(/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}\.\d{3}Z$/);
        expect(row?.["updated"]).toBe(row?.["created"]);

        // the reader finds the record through the link, and unlinks it
        const second = await start(reader, dataDir);
        try {
          const again = await signIn(second);
          expect(again.status).toBe(200);
          expect(again.json["meta"]).toMatchObject({ isNew: false });
          expect((again.json["record"] as { id: string }).id).toBe(recordId);
          expect(externalAuthRows(dataDir).length).toBe(1);

          const list = await api(
            second,
            "GET",
            `/api/collections/_externalAuths/records?filter=${encodeURIComponent(`recordRef="${recordId}"`)}`,
            undefined,
            { Authorization: token },
          );
          expect(list.json["totalItems"]).toBe(1);

          const removed = await api(
            second,
            "DELETE",
            `/api/collections/_externalAuths/records/${String(row?.["id"])}`,
            undefined,
            { Authorization: token },
          );
          expect(removed.status).toBe(204);
          expect(externalAuthRows(dataDir)).toEqual([]);

          // the verified email links the record again
          const relinked = await signIn(second);
          expect(relinked.json["meta"]).toMatchObject({ isNew: false });
          expect((relinked.json["record"] as { id: string }).id).toBe(recordId);
          expect(externalAuthRows(dataDir).length).toBe(1);
        } finally {
          await second.stop();
        }
      },
      timeout,
    );
  }
});

describe("what a sign-in triggers", () => {
  test(
    "the auth alert for a new origin",
    async () => {
      const sink = sharedSmtpSink();
      await onBoth(
        async (server) => {
          const before = sink.messages.length;
          const statuses: number[] = [];
          const counts: number[] = [];
          for (const agent of ["agent one", "agent two", "agent two"]) {
            statuses.push((await signIn(server, {}, { "User-Agent": agent })).status);
            await Bun.sleep(150);
            counts.push(sink.messages.length - before);
          }
          const mail = sink.messages.slice(before).map((m) => ({
            to: m.to,
            subject: /^Subject: (.*)$/m.exec(m.data)?.[1],
          }));
          return { statuses, counts, mail };
        },
        all(
          smtpToSink(),
          useProvider({ user: { sub: "alert", ...verifiedEmail("test2@example.com") } }, (c) => {
            c.authAlert.enabled = true;
          }),
        ),
      );
    },
    timeout,
  );

  test(
    "MFA: OAuth2 then password, password then OAuth2, and the same method twice",
    async () => {
      await onBoth(
        async (server) => {
          const password = (mfaId?: string): Promise<Reply> =>
            api(server, "POST", "/api/collections/users/auth-with-password", {
              identity: "test2@example.com",
              password: "1234567890",
              ...(mfaId === undefined ? {} : { mfaId }),
            });

          const first = await signIn(server);
          const mfaId = first.json["mfaId"] as string;
          const sameMethod = await signIn(server, { mfaId });
          const second = await password(mfaId);

          const third = await password();
          const inQuery = await signIn(server, {}, {}, `?mfaId=${third.json["mfaId"] as string}`);

          return { first, sameMethod, second, third, inQuery };
        },
        useProvider({ user: { sub: "mfa", ...verifiedEmail("test2@example.com") } }, (c) => {
          c.mfa.enabled = true;
          c.mfa.rule = "";
        }),
      );
    },
    timeout,
  );

  test(
    "realtime messages of a new user, and none of a refused one",
    async () => {
      await onBoth(
        async (server) => {
          const ctx = new ScenarioContext(server.url);
          try {
            const stream = await ctx.open();
            await ctx.subscribe(stream.clientId, ["users/*"], superuserToken);

            const refused = await signIn(server, { createData: { email: "invalid" } });
            const created = await signIn(server);
            await stream.waitFor((e) => e.length > 2);

            const list = actions(await settled(stream)).map((a) => a.replace(/ [a-z0-9]{15}$/, ""));
            return { refused, created, list };
          } finally {
            ctx.close();
          }
        },
        useProvider({ user: { sub: "live", ...verifiedEmail("live@example.com") } }),
      );
    },
    timeout,
  );

  test(
    "the record's old tokens after the verified upgrade",
    async () => {
      await onBoth(
        async (server) => {
          const headers = { Authorization: usersToken };
          const before = await api(
            server,
            "POST",
            "/api/collections/users/auth-refresh",
            undefined,
            headers,
          );
          const auth = await signIn(server);
          const after = await api(
            server,
            "POST",
            "/api/collections/users/auth-refresh",
            undefined,
            headers,
          );
          const newToken = await api(
            server,
            "POST",
            "/api/collections/users/auth-refresh",
            undefined,
            { Authorization: auth.json["token"] as string },
          );
          return { before: before.status, auth, after, newToken: newToken.status };
        },
        useProvider({ user: { sub: "upgrade", ...verifiedEmail("test@example.com") } }),
      );
    },
    timeout,
  );

  test(
    "a create rule that sees the auth state of the outer request",
    async () => {
      await onBoth(
        async (server, dataDir) => {
          const guest = await signIn(server);
          const logged = await signIn(
            server,
            { createData: {} },
            { Authorization: superuserToken },
          );
          return { guest, logged, links: externalAuthRows(dataDir).length };
        },
        useProvider({ user: { sub: "rule_user" } }, (c) => {
          c.createRule = `@request.auth.id != ""`;
        }),
      );
    },
    timeout,
  );
});
