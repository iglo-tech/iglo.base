const timeout = 120_000;

type Kind = "upstream" | "igloBase";

interface Server {
  url: string;
  stop(): Promise<unknown>;
}

const roots: string[] = [];

afterAll(() => {
  for (const root of roots) {
    rmSync(root, { recursive: true, force: true });
  }
});

// a fresh copy of the fixture's pb_data for one server of one run
function fixtureCopy(): string {
  const root = mkdtempSync(join(tmpdir(), "iglo-base-oauth2-providers-"));
  roots.push(root);
  const dataDir = join(root, "pb_data");
  copyDataDir(fixtureDir, dataDir);
  return dataDir;
}

const start = (kind: Kind, dataDir: string): Promise<Server> =>
  kind === "upstream" ? startUpstream({ dataDir }) : startServer([], dataDir);

// the transcript as comparable text: tokens, record ids, timestamps and
// autogenerated usernames replaced, object members sorted
function scrub(transcript: unknown): string {
  const sorted = (value: unknown): unknown => {
    if (Array.isArray(value)) {
      return value.map(sorted);
    }
    if (value !== null && typeof value === "object") {
      return Object.fromEntries(
        Object.entries(value)
          .toSorted(([a], [b]) => (a < b ? -1 : 1))
          .map(([k, v]) => [k, sorted(v)]),
      );
    }
    return value;
  };
  return JSON.stringify(sorted(transcript), null, 2)
    .replace(/\beyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+/g, "<token>")
    .replace(/\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}\.\d{3}Z/g, "<date>")
    .replace(/"(id|recordRef|mfaId)": "[a-z0-9]{15}"/g, '"$1": "<id>"')
    .replace(/users[0-9]{5}/g, "<username>")
    .replace(/\b[A-Za-z0-9]{40}\b/g, "<client>")
    .replace(/logo_[a-z0-9]{10}_[a-z0-9]{10}\.png/g, "<file>");
}

// what the mock saw of one provider, without its per-server ids
const seen = (requests: MockRequest[]) =>
  requests.map((r) => ({
    method: r.method,
    path: r.path,
    authorization: r.authorization,
    contentType: r.contentType,
    body: r.body,
  }));

const authURL = "/api/collections/users/auth-with-oauth2";

interface Transcript {
  status: number;
  json: unknown;
  requests: ReturnType<typeof seen>;
  links: unknown;
  users: unknown;
}

// the users and the external auth links of a stopped server's pb_data
function rowsOf(dataDir: string): { links: unknown; users: unknown } {
  const db = new Database(join(dataDir, "data.db"), { readonly: true });
  try {
    return {
      links: db
        .query(
          "SELECT provider, providerId, collectionRef FROM _externalAuths ORDER BY provider, providerId",
        )
        .all(),
      users: db
        .query(
          "SELECT email, verified, name, username, emailVisibility FROM users ORDER BY email, name",
        )
        .all(),
    };
  } finally {
    db.close();
  }
}

// one sign-in of case c on a server of the given kind
async function signIn(kind: Kind, c: ProviderCase): Promise<Transcript> {
  const dataDir = fixtureCopy();
  const mock = sharedOAuth2Mock().register({
    token: c.token ?? { access_token: "abc", token_type: "bearer" },
    user: c.user,
    userStatus: c.userStatus,
    emails: c.emails,
    emailsStatus: c.emailsStatus,
  });
  updateCollection(dataDir, "users", (collection) => {
    collection.mfa.enabled = false;
    collection.oauth2.enabled = true;
    collection.oauth2.providers = [
      new OAuth2ProviderConfig({
        name: c.provider,
        clientId: "123",
        clientSecret: "456",
        authURL: mock.authURL,
        tokenURL: mock.tokenURL,
        userInfoURL: mock.userInfoURL,
      }),
    ];
  });

  const server = await start(kind, dataDir);
  let status = 0;
  let json: unknown;
  try {
    const res = await fetch(server.url + authURL, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        provider: c.provider,
        code: "123",
        codeVerifier: "456",
        redirectURL: "https://example.com",
      }),
    });
    status = res.status;
    json = await res.json();
  } finally {
    await server.stop();
  }
  return {
    status,
    json,
    requests: seen(mock.requests),
    ...rowsOf(dataDir),
  };
}

describe("OAuth2 sign-in of each provider", () => {
  for (const c of providerCases) {
    test(
      c.name,
      async () => {
        const upstream = await signIn("upstream", c);
        const igloBase = await signIn("igloBase", c);

        // the case reaches its branch on the reference server
        expect(upstream.status).toBe(c.status);
        if (c.email !== undefined) {
          const record = (upstream.json as { record?: { email?: string } }).record;
          expect(record?.email ?? "").toBe(c.email);
        }

        expect(scrub(igloBase)).toBe(scrub(upstream));
      },
      timeout,
    );
  }
});

// the auth methods of every ported provider, with the defaults of the
// provider (no URL is configured): the names, display names, logos,
// endpoints, scopes and PKCE parameters the list shows
async function authMethods(kind: Kind): Promise<unknown> {
  const dataDir = fixtureCopy();
  updateCollection(dataDir, "users", (collection) => {
    collection.oauth2.enabled = true;
    collection.oauth2.providers = authMethodsProviders.map(
      (name) => new OAuth2ProviderConfig({ name, clientId: "123", clientSecret: "456" }),
    );
  });

  const server = await start(kind, dataDir);
  try {
    const res = await fetch(`${server.url}/api/collections/users/auth-methods`);
    expect(res.status).toBe(200);
    const body = (await res.json()) as {
      oauth2: { providers: { [key: string]: unknown }[] };
    };
    // state and the PKCE values are generated for each request
    return body.oauth2.providers.map((p) => ({
      ...p,
      state: "<state>",
      authURL: normalizeAuthURL(p["authURL"] as string),
      authUrl: normalizeAuthURL(p["authUrl"] as string),
      codeVerifier: p["codeVerifier"] === "" ? "" : "<verifier>",
      codeChallenge: p["codeChallenge"] === "" ? "" : "<challenge>",
    }));
  } finally {
    await server.stop();
  }
}

function normalizeAuthURL(url: string): string {
  return url
    .replace(/([?&])state=[^&]*/, "$1state=<state>")
    .replace(/([?&])code_challenge=[^&]*/, "$1code_challenge=<challenge>");
}

describe("auth methods defaults", () => {
  test(
    "every ported provider lists the same defaults as upstream",
    async () => {
      const upstream = await authMethods("upstream");
      const igloBase = await authMethods("igloBase");
      expect(upstream).toHaveLength(authMethodsProviders.length);
      expect(scrub(igloBase)).toBe(scrub(upstream));
    },
    timeout,
  );
});

// Apple's client secret: upstream and iglo.base sign with the same key, the
// secrets verify with its public key, and the header and claims agree with
// upstream (the times aside)
function decodeJWT(token: string): {
  header: Record<string, unknown>;
  claims: Record<string, unknown>;
  signingInput: string;
  signature: Buffer;
  raw: { header: string; claims: string };
} {
  const [h = "", c = "", s = ""] = token.split(".");
  return {
    header: JSON.parse(Buffer.from(h, "base64url").toString()),
    claims: JSON.parse(Buffer.from(c, "base64url").toString()),
    signingInput: `${h}.${c}`,
    signature: Buffer.from(s, "base64url"),
    raw: {
      header: Buffer.from(h, "base64url").toString(),
      claims: Buffer.from(c, "base64url").toString(),
    },
  };
}

async function generateSecret(kind: Kind, privateKey: string): Promise<string> {
  const dataDir = fixtureCopy();
  const server = await start(kind, dataDir);
  try {
    const res = await fetch(`${server.url}/api/settings/apple/generate-client-secret`, {
      method: "POST",
      headers: { "Content-Type": "application/json", Authorization: superuserToken },
      body: JSON.stringify({
        clientId: "com.example.app",
        teamId: "ABCDE12345",
        keyId: "KEYID12345",
        privateKey,
        duration: 3600,
      }),
    });
    expect(res.status).toBe(200);
    return ((await res.json()) as { secret: string }).secret;
  } finally {
    await server.stop();
  }
}

describe("Apple client secret", () => {
  test(
    "the secret verifies with the key and carries upstream's header and claims",
    async () => {
      const privateKey = appleSecretPrivateKey();
      const upstream = decodeJWT(await generateSecret("upstream", privateKey));
      const igloBase = decodeJWT(await generateSecret("igloBase", privateKey));

      expect(igloBase.header).toEqual(upstream.header);
      expect(igloBase.raw.header).toBe(upstream.raw.header);
      // the same members in the same order, the same audience form
      expect(Object.keys(igloBase.claims)).toEqual(Object.keys(upstream.claims));
      expect(igloBase.raw.claims.replace(/"(iat|exp)":\d+/g, "")).toBe(
        upstream.raw.claims.replace(/"(iat|exp)":\d+/g, ""),
      );
      expect(igloBase.claims["exp"] as number).toBe((igloBase.claims["iat"] as number) + 3600);
      expect(upstream.claims["exp"] as number).toBe((upstream.claims["iat"] as number) + 3600);

      // raw r||s signatures, checked with the public key
      const publicKey = createPublicKey(privateKey);
      for (const secret of [igloBase, upstream]) {
        expect(secret.signature.length).toBe(64);
        expect(
          verify(
            "sha256",
            Buffer.from(secret.signingInput),
            { key: publicKey, dsaEncoding: "ieee-p1363" },
            secret.signature,
          ),
        ).toBe(true);
      }
    },
    timeout,
  );
});
