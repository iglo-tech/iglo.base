const text = (b: Uint8Array) => bytesToText(b);

function chunks(data: Uint8Array, size: (left: number) => number): ReadableStream<Uint8Array> {
  let off = 0;
  return new ReadableStream({
    pull(controller) {
      if (off >= data.length) {
        controller.close();
        return;
      }
      const n = size(data.length - off);
      controller.enqueue(data.slice(off, off + n));
      off += n;
    },
  });
}

describe("TestDetect", () => {
  test.each(testcases)("%s", async (_name, data, expectedMIME) => {
    expect(detect(data).string()).toBe(expectedMIME);
    const [mtype, err] = await detectReader(chunks(data, (left) => left));
    expect(err).toBeNull();
    expect(mtype.string()).toBe(expectedMIME);
    const [fromBlob, blobErr] = await detectReader(new Blob([data]));
    expect(blobErr).toBeNull();
    expect(fromBlob.string()).toBe(expectedMIME);
  });
});

