function xmlMIME(mime: string, aliases: string[]): MIME {
  const m = new MIME(mime, ".xml", null);
  m.aliases = aliases;
  return m;
}

describe("TestIs", () => {
  const tcases: [name: string, m: MIME, n: string, expected: boolean][] = [
    ["mime matches", xmlMIME("text/xml", ["application/xml"]), "text/xml", true],
    ["alias matches", xmlMIME("text/xml", ["application/xml"]), "application/xml", true],
    [
      "mime matches because both m.mime and n are converted to lower case",
      xmlMIME("Text/xml", ["application/xml"]),
      "tEXT/XML",
      true,
    ],
    [
      "alias matches because n is converted to lower case",
      xmlMIME("text/xml", ["application/xml"]),
      "Application/xml",
      true,
    ],
    [
      "alias does not match because aliases are not converted to lower case",
      xmlMIME("text/xml", ["Application/xml"]),
      "Application/xml",
      false,
    ],
    ["empty string does not match anything", xmlMIME("text/xml", ["application/xml"]), "", false],
  ];
  test.each(tcases)("%s", (_name, m, n, expected) => {
    expect(m.is(n)).toBe(expected);
  });
});

