test("TestSaltedCipher", () => {
  const key = new Uint8Array(32);
  const salt = new Uint8Array(32);
  for (let i = 0; i < key.length; i++) {
    key[i] = i;
    salt[i] = i + 32;
  }
  for (const [i, v] of saltedVectors.entries()) {
    const c = NewSaltedCipher(key, salt.subarray(0, i));
    const buf = new Uint8Array(8);
    c.encrypt(buf, buf);
    expect({ i, buf: [...buf] }).toEqual({ i, buf: v });
  }
});

