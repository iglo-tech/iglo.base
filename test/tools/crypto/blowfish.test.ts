test("TestCipherEncrypt", () => {
  for (const [i, [key, input, out]] of encryptTests.entries()) {
    const c = NewCipher(Uint8Array.from(key));
    const ct = new Uint8Array(out.length);
    c.encrypt(ct, Uint8Array.from(input));
    expect({ i, ct: [...ct] }).toEqual({ i, ct: out });
  }
});

test("TestCipherDecrypt", () => {
  for (const [i, [key, input, out]] of encryptTests.entries()) {
    const c = NewCipher(Uint8Array.from(key));
    const pt = new Uint8Array(input.length);
    c.decrypt(pt, Uint8Array.from(out));
    expect({ i, pt: [...pt] }).toEqual({ i, pt: input });
  }
});

test("TestSaltedCipherKeyLength", () => {
  expect(() => NewSaltedCipher(new Uint8Array(0), Uint8Array.of(0x61))).toThrow(
    new KeySizeError(0),
  );

  // A 57-byte key. One over the typical blowfish restriction.
  const key = new TextEncoder().encode("012345678901234567890123456789012345678901234567890123456");
  expect(() => NewSaltedCipher(key, Uint8Array.of(0x61))).not.toThrow();
});

