// Generates src/tools/unicode/tables.ts from Go's src/unicode/tables.go, so
// regexp/syntax uses the Unicode version of the Go toolchain upstream was
// built with (go1.27.2), not the one of the JS engine.
//
//   bun scripts/unicode/generate-tables.ts [go checkout] [output file]
//
// The go checkout defaults to .upstream/deps/go, a shallow clone of
// https://github.com/golang/go at tag go1.27.2. Only what regexp/syntax
// needs is written: the Categories, Scripts, FoldCategory and FoldScript
// tables, CategoryAliases, the CaseRanges, caseOrbit and asciiFold tables
// behind SimpleFold, and the printable flag of the Latin-1 properties
// table (IsPrint). The output is deterministic: entries keep their order in
// tables.go.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const expectedGoVersion = "go1.27.2";

const goRoot = process.argv[2] ?? join(import.meta.dir, "..", "..", ".upstream", "deps", "go");
const outFile =
  process.argv[3] ?? join(import.meta.dir, "..", "..", "src", "tools", "unicode", "tables.ts");

const goVersion = (readFileSync(join(goRoot, "VERSION"), "utf8").split("\n")[0] ?? "").trim();
if (goVersion !== expectedGoVersion) {
  throw new Error(`expected Go ${expectedGoVersion} in ${goRoot}, found ${goVersion}`);
}
const src = readFileSync(join(goRoot, "src", "unicode", "tables.go"), "utf8");

// the body of `var <name> = <prefix>{ ... }` up to the matching closing brace
function block(name: string): string {
  const start = src.search(new RegExp(`^var ${name} = [^\\n]*\\{$`, "m"));
  if (start < 0) {
    throw new Error(`var ${name} not found`);
  }
  const open = src.indexOf("{\n", start) + 1;
  let depth = 1;
  for (let i = open; i < src.length; i++) {
    if (src[i] === "{") {
      depth++;
    } else if (src[i] === "}" && --depth === 0) {
      return src.slice(open, i);
    }
  }
  throw new Error(`var ${name} is not closed`);
}

// `"key": value,` entries of a map literal, in source order
function mapEntries(name: string): [string, string][] {
  return [...block(name).matchAll(/^\t"([^"]+)":\s*(.+),$/gm)].map((m) => [
    m[1] as string,
    (m[2] as string).replace(/^"|"$/g, ""),
  ]);
}

// the `X = _Y` aliases in the `var ( ... )` blocks
const aliases = new Map<string, string>();
for (const m of src.matchAll(/^\t(\w+)\s*= (_\w+)/gm)) {
  aliases.set(m[1] as string, m[2] as string);
}

// a range table as "lo-hi/stride" hex triples (R16 then R32), "lo" when
// lo == hi and "/stride" left out when it is 1
function rangeTable(ident: string): string {
  const name = aliases.get(ident) ?? ident;
  const body = block(name);
  const out: string[] = [];
  for (const m of body.matchAll(/\{(0x[0-9a-f]+), (0x[0-9a-f]+), (\d+)\}/g)) {
    const lo = Number(m[1]);
    const hi = Number(m[2]);
    const stride = Number(m[3]);
    out.push(
      (lo === hi ? lo.toString(16) : `${lo.toString(16)}-${hi.toString(16)}`) +
        (stride === 1 ? "" : `/${stride.toString(16)}`),
    );
  }
  return out.join(",");
}

function tableMap(name: string): string {
  const lines = mapEntries(name).map(
    ([key, ident]) => `  ${key}: ${JSON.stringify(rangeTable(ident))},`,
  );
  return `{\n${lines.join("\n")}\n}`;
}

const categoryAliases = mapEntries("CategoryAliases")
  .map(([key, value]) => `  ${key}: ${JSON.stringify(value)},`)
  .join("\n");

// CaseRanges: lo, hi and the three deltas; UpperLower is written as "UL"
const caseRanges = [
  ...block("_CaseRanges").matchAll(/\{0x([0-9A-F]+), 0x([0-9A-F]+), d\{([^}]*)\}\}/g),
]
  .map((m) => {
    const deltas = (m[3] as string).split(", ").map((d) => (d === "UpperLower" ? "UL" : d));
    return [(m[1] as string).toLowerCase(), (m[2] as string).toLowerCase(), ...deltas].join(" ");
  })
  .join(",");

const caseOrbit = [...block("caseOrbit").matchAll(/\{0x([0-9A-F]+), 0x([0-9A-F]+)\}/g)]
  .map((m) => `${(m[1] as string).toLowerCase()} ${(m[2] as string).toLowerCase()}`)
  .join(",");

const asciiFold = [...block("asciiFold").matchAll(/0x([0-9A-F]{4}),/g)]
  .map((m) => Number.parseInt(m[1] as string, 16).toString(16))
  .join(",");
if (asciiFold.split(",").length !== 128) {
  throw new Error("asciiFold must have 128 entries");
}

// Latin-1 code points whose properties entry has the pp (printable) bit
const printLatin1: number[] = [];
for (const m of block("properties").matchAll(/^\t0x([0-9A-F]{2}): ([^,]+),/gm)) {
  if (/\bpp\b|\bpg\b/.test(m[2] as string)) {
    printLatin1.push(Number.parseInt(m[1] as string, 16));
  }
}

const version = /^const Version = "([^"]+)"$/m.exec(src)?.[1];
if (version === undefined) {
  throw new Error("Unicode Version not found");
}

const out = `// Code generated by scripts/unicode/generate-tables.ts from Go ${goVersion}
// src/unicode/tables.go (Unicode ${version}); DO NOT EDIT.
//
// Range tables are lists of "lo-hi/stride" hex ranges (R16 then R32), with
// "lo" for lo == hi and no "/stride" when the stride is 1.

// Version is the Unicode edition from which the tables are derived.
export const Version = ${JSON.stringify(version)};

// Categories is the set of Unicode category tables.
export const Categories: Record<string, string> = ${tableMap("Categories")};

// CategoryAliases maps category aliases to standard category names.
export const CategoryAliases: Record<string, string> = {
${categoryAliases}
};

// Scripts is the set of Unicode script tables.
export const Scripts: Record<string, string> = ${tableMap("Scripts")};

// FoldCategory maps a category name to a table of code points outside the
// category that are equivalent under simple case folding to code points
// inside the category.
export const FoldCategory: Record<string, string> = ${tableMap("FoldCategory")};

// FoldScript maps a script name to a table of code points outside the
// script that are equivalent under simple case folding to code points inside
// the script.
export const FoldScript: Record<string, string> = ${tableMap("FoldScript")};

// CaseRanges: "lo hi upper lower title" (hex bounds, decimal deltas, UL for
// UpperLower), comma separated.
export const CaseRanges = ${JSON.stringify(caseRanges)};

// caseOrbit: "from to" hex pairs, comma separated.
export const caseOrbit = ${JSON.stringify(caseOrbit)};

// asciiFold: SimpleFold of each ASCII code point, hex, comma separated.
export const asciiFold = ${JSON.stringify(asciiFold)};

// The Latin-1 code points with the pp (printable) bit in Go's properties
// table.
export const printLatin1 = ${JSON.stringify(rangesOf(printLatin1))};
`;

// consecutive code points as "lo-hi" hex ranges
function rangesOf(points: number[]): string {
  const ranges: string[] = [];
  for (let i = 0; i < points.length;) {
    let j = i;
    while (j + 1 < points.length && points[j + 1] === (points[j] as number) + 1) {
      j++;
    }
    const lo = points[i] as number;
    const hi = points[j] as number;
    ranges.push(lo === hi ? lo.toString(16) : `${lo.toString(16)}-${hi.toString(16)}`);
    i = j + 1;
  }
  return ranges.join(",");
}

writeFileSync(outFile, out);

// format as the repository does, so a regenerated file passes format:check
const fmt = Bun.spawnSync([
  join(import.meta.dir, "..", "..", "node_modules", ".bin", "oxfmt"),
  outFile,
]);
if (fmt.exitCode !== 0) {
  throw new Error(`oxfmt failed: ${fmt.stderr.toString()}`);
}
